#!/usr/bin/env python3
"""Generate a custom Bluetooth GATT service for one stack from a small JSON description.

  python3 tools/gatt_gen/gatt_gen.py tools/gatt_gen/blinky.json --target ti-ble5stack --out <dir>
  python3 tools/gatt_gen/gatt_gen.py tools/gatt_gen/blinky.json --target zephyr --out <dir>

Writes <name>_service.c and <name>_service.h. The format is in service.schema.md.
Targets: ti-ble5stack (TI BLE5-Stack, SimpleLink CC13xx CC26xx SDK 8.33), ti-f3 (TI BLE stack in the
SimpleLink Low Power F3 SDK 9.21, CC23xx/CC27xx) and zephyr (Zephyr 4.x).
Standard library only.
"""
import argparse, json, pathlib, re, sys, uuid

PROPS = ["read", "write", "write-no-response", "notify", "indicate"]
TOOL = "tools/gatt_gen/gatt_gen.py"


def fail(msg):
    sys.exit(f"gatt_gen: {msg}")


def words(name):
    w = re.findall(r"[A-Za-z0-9]+", name)
    if not w or not w[0][0].isalpha():
        fail(f"name {name!r} must start with a letter")
    return w


def names(name):
    w = words(name)
    camel = "".join(x[0].upper() + x[1:].lower() for x in w)
    return {"camel": camel, "lower": camel[0].lower() + camel[1:],
            "upper": "_".join(x.upper() for x in w), "snake": "_".join(x.lower() for x in w)}


def load(path):
    try:
        d = json.loads(pathlib.Path(path).read_text())
    except (OSError, ValueError) as e:
        fail(f"{path}: {e}")
    for key in ("service", "uuid", "characteristics"):
        if key not in d:
            fail(f"missing field {key!r}")
    extra = set(d) - {"service", "uuid", "characteristics"}
    if extra:
        fail(f"unknown field(s) {sorted(extra)}")
    d["n"] = names(d["service"])
    d["u"] = parse_uuid(d["uuid"], "service")
    seen = set()
    if not d["characteristics"]:
        fail("a service needs at least one characteristic")
    for i, c in enumerate(d["characteristics"]):
        extra = set(c) - {"name", "uuid", "properties", "length", "description", "variable"}
        if extra:
            fail(f"characteristic {i}: unknown field(s) {sorted(extra)}")
        for key in ("name", "uuid", "properties", "length"):
            if key not in c:
                fail(f"characteristic {i}: missing field {key!r}")
        c["n"] = names(c["name"])
        c["u"] = parse_uuid(c["uuid"], c["name"])
        if c["n"]["upper"] in seen or c["u"] == d["u"]:
            fail(f"characteristic {c['name']!r}: name or UUID used twice")
        seen.add(c["n"]["upper"])
        bad = [p for p in c["properties"] if p not in PROPS]
        if bad or not c["properties"]:
            fail(f"characteristic {c['name']!r}: properties must be some of {PROPS}, got {c['properties']}")
        if not isinstance(c["length"], int) or not 1 <= c["length"] <= 512:
            fail(f"characteristic {c['name']!r}: length must be 1 to 512 bytes")
        if "description" in c and (not isinstance(c["description"], str) or '"' in c["description"] or "\\" in c["description"]):
            fail(f"characteristic {c['name']!r}: description must be a string without quotes or backslashes")
        if "variable" in c and not isinstance(c["variable"], bool):
            fail(f"characteristic {c['name']!r}: variable must be true or false")
        c["variable"] = bool(c.get("variable", False))
        c["id"] = i
        c["writable"] = "write" in c["properties"] or "write-no-response" in c["properties"]
        c["cccd"] = "notify" in c["properties"] or "indicate" in c["properties"]
    if len({str(c["u"]) for c in d["characteristics"]}) != len(d["characteristics"]):
        fail("two characteristics share a UUID")
    return d


def parse_uuid(text, what):
    if not re.fullmatch(r"[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}", str(text)):
        fail(f"{what}: {text!r} is not a 128-bit UUID like de8a5aac-a99b-c315-0c80-60d4cbb51224")
    return uuid.UUID(text)


def air_bytes(u):
    """Bluetooth sends a 128-bit UUID low byte first: the string's bytes reversed.
    (Python's uuid.bytes_le is a different, mixed order. Do not use it here.)"""
    return u.bytes[::-1]


def c_bytes(u, indent):
    b = ["0x%02x" % x for x in air_bytes(u)]
    return ", ".join(b[:8]) + ", \\\n" + " " * indent + ", ".join(b[8:])


def header_banner(d, src, target):
    return (f"/*\n * {d['n']['snake']}_service: generated by {TOOL} from {src}.\n"
            f" * Target: {target}.\n"
            f" * Do not edit by hand: change the JSON and run the generator again.\n */\n")


def props_text(c):
    return ", ".join(c["properties"]) + f"; {c['length']} byte" + ("s" if c["length"] > 1 else "")


# ---------------------------------------------------------------- TI BLE5-Stack

def ti(d, src, f3=False):
    n, chars = d["n"], d["characteristics"]
    KW = "const" if f3 else "CONST"
    P, p, U = n["camel"] + "Service", n["lower"], n["upper"]
    banner = header_banner(d, src, "TI BLE stack, SimpleLink Low Power F3 SDK 9.21 (CC23xx, CC27xx)" if f3 else
                           "TI BLE5-Stack, SimpleLink CC13xx CC26xx SDK 8.33 (ble5stack_flash)")
    ind = len(f"#define {U}_SERV_UUID128 ")
    h = [banner, f"#ifndef {U}_SERVICE_H", f"#define {U}_SERVICE_H", "",
         "#include <stdint.h>", ("#include \"ti/ble/stack_util/icall/app/icall_ble_api.h\"" if f3 else "#include <bcomdef.h>"), "",
         "/* 128-bit UUIDs, low byte first as they go on the air. */",
         f"/* Service {d['u']} */", f"#define {U}_SERV_UUID128 {c_bytes(d['u'], ind)}"]
    for c in chars:
        C = f"{U}_{c['n']['upper']}"
        h += [f"/* {c['name']}: {props_text(c)}. {c['u']} */",
              f"#define {C}_UUID128 {c_bytes(c['u'], len(f'#define {C}_UUID128 '))}",
              f"#define {C}_ID  {c['id']}", f"#define {C}_LEN {c['length']}" + (" /* largest value; a peer may write fewer bytes */" if c["variable"] else "")]
    h += ["", "/* Called after a peer writes a characteristic (charId is one of the _ID values).",
          " * Runs in the BLE stack's context: keep it short or post to your own task. */",
          f"typedef void (*{P}_ChangeCb_t)(uint16_t connHandle, uint8_t charId, uint16_t len, uint8_t *pValue);", "",
          "/* Register the service with the GATT server. changeCb may be NULL. */",
          f"bStatus_t {P}_AddService(uint8_t rspTaskId, {P}_ChangeCb_t changeCb);", "",
          "/* Set or get a value. len must equal the characteristic's _LEN" + (" (a variable-length one takes 1 to _LEN bytes)" if any(c["variable"] for c in chars) else "") + ". */"]
    for c in chars:
        k = c["n"]["camel"]
        h += [f"bStatus_t {P}_Set{k}(const void *value, uint16_t len);",
              f"bStatus_t {P}_Get{k}(void *value, uint16_t *len);"]
        if c["cccd"]:
            h += [f"/* Send the current {c['name']} value to every peer that turned on notifications or indications. */",
                  f"bStatus_t {P}_Notify{k}(void);"]
    h += ["", f"#endif /* {U}_SERVICE_H */", ""]

    s = [banner, "#include <string.h>"] + (['#include "ti/ble/stack_util/icall/app/icall.h"', '#include "ti/ble/stack_util/icall/app/icall_ble_api.h"'] if f3 else ["#include <icall.h>", '#include "icall_ble_api.h"']) + [""] + [
         f'#include "{n["snake"]}_service.h"', "",
         f"static {KW} uint8_t {p}ServUUID[ATT_UUID_SIZE] = {{ {U}_SERV_UUID128 }};"]
    for c in chars:
        s.append(f"static {KW} uint8_t {p}{c['n']['camel']}UUID[ATT_UUID_SIZE] = {{ {U}_{c['n']['upper']}_UUID128 }};")
    s += ["", f"static {KW} gattAttrType_t {p}ServDecl = {{ ATT_UUID_SIZE, {p}ServUUID }};", ""]
    gp = {"read": "GATT_PROP_READ", "write": "GATT_PROP_WRITE", "write-no-response": "GATT_PROP_WRITE_NO_RSP",
          "notify": "GATT_PROP_NOTIFY", "indicate": "GATT_PROP_INDICATE"}
    for c in chars:
        k, C = c["n"]["camel"], f"{U}_{c['n']['upper']}"
        s += [f"/* {c['name']}: {props_text(c)} */",
              f"static uint8_t {p}{k}Props = {' | '.join(gp[x] for x in PROPS if x in c['properties'])};",
              f"static uint8_t {p}{k}Val[{C}_LEN];"]
        if c["variable"]:
            s.append(f"static uint16_t {p}{k}Len = 0; /* bytes in use, 1 to {C}_LEN */")
        if c["cccd"]:
            s.append(f"static gattCharCfg_t *{p}{k}Cfg;")
        if "description" in c:
            s.append(f'static uint8_t {p}{k}Desc[] = "{c["description"]}";')
    s += ["", f"static {P}_ChangeCb_t {p}ChangeCb = NULL;", f"static uint8_t {p}RspTaskId = INVALID_TASK_ID;", "",
          f"static gattAttribute_t {p}AttrTbl[] =", "{",
          f"    {{ {{ ATT_BT_UUID_SIZE, primaryServiceUUID }}, GATT_PERMIT_READ, 0, (uint8_t *)&{p}ServDecl }},"]
    for c in chars:
        k = c["n"]["camel"]
        perm = " | ".join(x for x in ["GATT_PERMIT_READ" if "read" in c["properties"] else "",
                                      "GATT_PERMIT_WRITE" if c["writable"] else ""] if x) or "0"
        s += [f"    /* {c['name']} */",
              f"    {{ {{ ATT_BT_UUID_SIZE, characterUUID }}, GATT_PERMIT_READ, 0, &{p}{k}Props }},",
              f"    {{ {{ ATT_UUID_SIZE, {p}{k}UUID }}, {perm}, 0, {p}{k}Val }},"]
        if c["cccd"]:  # right after the value: the write callback finds the characteristic at pAttr - 1
            s.append(f"    {{ {{ ATT_BT_UUID_SIZE, clientCharCfgUUID }}, GATT_PERMIT_READ | GATT_PERMIT_WRITE, 0, (uint8_t *)&{p}{k}Cfg }},")
        if "description" in c:
            s.append(f"    {{ {{ ATT_BT_UUID_SIZE, charUserDescUUID }}, GATT_PERMIT_READ, 0, {p}{k}Desc }},")
    s += ["};", ""]

    # value attribute -> characteristic id, by UUID
    s += [f"static uint8_t {p}_findCharId(gattAttribute_t *pAttr)", "{",
          "    if (pAttr->type.len == ATT_UUID_SIZE)", "    {"]
    for c in chars:
        s += [f"        if (!memcmp(pAttr->type.uuid, {p}{c['n']['camel']}UUID, ATT_UUID_SIZE))",
              f"        {{", f"            return {U}_{c['n']['upper']}_ID;", "        }"]
    s += ["    }", "    return 0xFF;", "}", ""]

    def is16(uuid_macro):
        return (f"pAttr->type.len == ATT_BT_UUID_SIZE &&\n"
                f"        BUILD_UINT16(pAttr->type.uuid[0], pAttr->type.uuid[1]) == {uuid_macro}")

    s += [f"static bStatus_t {p}_ReadAttrCB(uint16_t connHandle, gattAttribute_t *pAttr,",
          f"{' ' * (len(p) + 29)}uint8_t *pValue, uint16_t *pLen, uint16_t offset,",
          f"{' ' * (len(p) + 29)}uint16_t maxLen, uint8_t method)", "{",
          "    uint16_t valueLen;", "    (void)connHandle; (void)method;"]
    if any("description" in c for c in chars):
        s += ["    if (" + is16("GATT_CHAR_USER_DESC_UUID") + ")", "    {",
              "        valueLen = (uint16_t)strlen((char *)pAttr->pValue);", "    }",
              "    else", "    {", f"        switch ({p}_findCharId(pAttr))", "        {"]
        pad = "    "
    else:
        s += [f"    switch ({p}_findCharId(pAttr))", "    {"]
        pad = ""
    for c in chars:
        C = f"{U}_{c['n']['upper']}"
        s.append(f"{pad}    case {C}_ID: valueLen = " + (f"{p}{c['n']['camel']}Len" if c["variable"] else f"{C}_LEN") + "; break;")
    s += [f"{pad}    default: return ATT_ERR_ATTR_NOT_FOUND;", f"{pad}    }}"]
    if pad:
        s.append("    }")
    s += ["    if (offset > valueLen)", "    {", "        return ATT_ERR_INVALID_OFFSET;", "    }",
          ("    *pLen = (maxLen < valueLen - offset) ? maxLen : (valueLen - offset);" if f3 else
           "    *pLen = MIN(maxLen, valueLen - offset);"), "    memcpy(pValue, pAttr->pValue + offset, *pLen);",
          "    return SUCCESS;", "}", ""]

    s += [f"static bStatus_t {p}_WriteAttrCB(uint16_t connHandle, gattAttribute_t *pAttr,",
          f"{' ' * (len(p) + 30)}uint8_t *pValue, uint16_t len, uint16_t offset,",
          f"{' ' * (len(p) + 30)}uint8_t method)", "{", "    (void)method;"]
    cccs = [c for c in chars if c["cccd"]]
    if cccs:
        s += ["    if (" + is16("GATT_CLIENT_CHAR_CFG_UUID") + ")", "    {", "        uint16_t allowed;",
              f"        switch ({p}_findCharId(pAttr - 1))", "        {"]
        for c in cccs:
            bits = " | ".join(b for x, b in [("notify", "GATT_CLIENT_CFG_NOTIFY"), ("indicate", "GATT_CLIENT_CFG_INDICATE")]
                              if x in c["properties"])
            s.append(f"        case {U}_{c['n']['upper']}_ID: allowed = {bits}; break;")
        s += ["        default: return ATT_ERR_ATTR_NOT_FOUND;", "        }",
              "        return GATTServApp_ProcessCCCWriteReq(connHandle, pAttr, pValue, len, offset, allowed);", "    }"]
    wr = [c for c in chars if c["writable"]]
    if wr:
        anyvar = any(c["variable"] for c in wr)
        s += ["    uint16_t valueLen;"] + (["    uint8_t isVar = 0;"] if anyvar else []) + [f"    uint8_t charId = {p}_findCharId(pAttr);", "    switch (charId)", "    {"]
        for c in wr:
            C = f"{U}_{c['n']['upper']}"
            s.append(f"    case {C}_ID: valueLen = {C}_LEN;" + (" isVar = 1;" if c["variable"] else "") + " break;")
        s += ["    default: return ATT_ERR_ATTR_NOT_FOUND;", "    }",
              "    if (offset != 0)", "    {", "        return ATT_ERR_ATTR_NOT_LONG;", "    }"]
        s += (["    if (isVar ? (len == 0 || len > valueLen) : (len != valueLen))"] if anyvar else ["    if (len != valueLen)"])
        s += ["    {", "        return ATT_ERR_INVALID_VALUE_SIZE;", "    }",
              "    memcpy(pAttr->pValue, pValue, len);"]
        for c in wr:
            if c["variable"]:
                s.append(f"    if (charId == {U}_{c['n']['upper']}_ID)\n    {{\n        {p}{c['n']['camel']}Len = len;\n    }}".replace("\\n","\n"))
        s += [f"    if ({p}ChangeCb)", "    {",
              f"        {p}ChangeCb(connHandle, charId, len, pAttr->pValue);", "    }", "    return SUCCESS;", "}", ""]
    else:
        s += ["    (void)connHandle; (void)pAttr; (void)pValue; (void)len; (void)offset;",
              "    return ATT_ERR_ATTR_NOT_FOUND;", "}", ""]

    s += [f"static {KW} gattServiceCBs_t {p}CBs = {{ {p}_ReadAttrCB, {p}_WriteAttrCB, NULL }};", "",
          f"bStatus_t {P}_AddService(uint8_t rspTaskId, {P}_ChangeCb_t changeCb)", "{"]
    for c in cccs:
        cfg = f"{p}{c['n']['camel']}Cfg"
        s += [f"    {cfg} = (gattCharCfg_t *)ICall_malloc(sizeof(gattCharCfg_t) * " + ("MAX_NUM_BLE_CONNS" if f3 else "linkDBNumConns") + ");",
              f"    if ({cfg} == NULL)", "    {", "        return bleMemAllocError;", "    }",
              f"    GATTServApp_InitCharCfg(LINKDB_CONNHANDLE_INVALID, {cfg});"]
    s += [f"    {p}ChangeCb = changeCb;", f"    {p}RspTaskId = rspTaskId;",
          f"    return GATTServApp_RegisterService({p}AttrTbl, GATT_NUM_ATTRS({p}AttrTbl),",
          f"                                       GATT_MAX_ENCRYPT_KEY_SIZE, &{p}CBs);", "}"]
    for c in chars:
        k, C, v = c["n"]["camel"], f"{U}_{c['n']['upper']}", f"{p}{c['n']['camel']}Val"
        if c["variable"]:
            L = f"{p}{k}Len"
            s += ["", f"bStatus_t {P}_Set{k}(const void *value, uint16_t len)", "{",
                  f"    if (len == 0 || len > {C}_LEN)", "    {", "        return bleInvalidRange;", "    }",
                  f"    memcpy({v}, value, len);", f"    {L} = len;", "    return SUCCESS;", "}", "",
                  f"bStatus_t {P}_Get{k}(void *value, uint16_t *len)", "{",
                  f"    if (*len < {L})", "    {", "        return bleInvalidRange;", "    }",
                  f"    memcpy(value, {v}, {L});", f"    *len = {L};", "    return SUCCESS;", "}"]
        else:
            s += ["", f"bStatus_t {P}_Set{k}(const void *value, uint16_t len)", "{",
                  f"    if (len != {C}_LEN)", "    {", "        return bleInvalidRange;", "    }",
                  f"    memcpy({v}, value, len);", "    return SUCCESS;", "}", "",
                  f"bStatus_t {P}_Get{k}(void *value, uint16_t *len)", "{",
                  f"    if (*len < {C}_LEN)", "    {", "        return bleInvalidRange;", "    }",
                  f"    memcpy(value, {v}, {C}_LEN);", f"    *len = {C}_LEN;", "    return SUCCESS;", "}"]
        if c["cccd"]:
            s += ["", f"bStatus_t {P}_Notify{k}(void)", "{",
                  f"    return GATTServApp_ProcessCharCfg({p}{k}Cfg, {v}, FALSE, {p}AttrTbl,",
                  f"                                      GATT_NUM_ATTRS({p}AttrTbl), {p}RspTaskId, {p}_ReadAttrCB);", "}"]
    s.append("")
    return "\n".join(h), "\n".join(s)


# ---------------------------------------------------------------- Zephyr

def zephyr(d, src):
    n, chars = d["n"], d["characteristics"]
    p, U = n["snake"], n["upper"]
    banner = header_banner(d, src, "Zephyr 4.x Bluetooth host (zephyr/bluetooth/gatt.h)")
    h = [banner, f"#ifndef {U}_SERVICE_H", f"#define {U}_SERVICE_H", "",
         "#include <stdint.h>", "#include <zephyr/bluetooth/conn.h>", ""]
    for c in chars:
        C = f"{U}_{c['n']['upper']}"
        h += [f"/* {c['name']}: {props_text(c)}. {c['u']} */", f"#define {C}_ID  {c['id']}", f"#define {C}_LEN {c['length']}"]
    h += ["", "/* Called after a peer writes a characteristic (char_id is one of the _ID values). */",
          f"typedef void (*{p}_change_cb_t)(struct bt_conn *conn, uint8_t char_id, uint16_t len, const uint8_t *value);",
          "", "/* The service is registered at build time; this only sets the callback (may be NULL). */",
          f"void {p}_service_init({p}_change_cb_t cb);"]
    for c in chars:
        k = c["n"]["snake"]
        h += [f"int {p}_service_set_{k}(const void *value, uint16_t len);",
              f"int {p}_service_get_{k}(void *value, uint16_t *len);"]
        if "notify" in c["properties"]:
            h.append(f"int {p}_service_notify_{k}(void);")
        if "indicate" in c["properties"]:
            h.append(f"int {p}_service_indicate_{k}(void);")
    h += ["", f"#endif /* {U}_SERVICE_H */", ""]

    def enc(u):
        x = u.hex
        return f"BT_UUID_128_ENCODE(0x{x[:8]}, 0x{x[8:12]}, 0x{x[12:16]}, 0x{x[16:20]}, 0x{x[20:]})"

    s = [banner, "#include <errno.h>", "#include <string.h>", "#include <zephyr/bluetooth/gatt.h>",
         "#include <zephyr/bluetooth/uuid.h>", "", f'#include "{p}_service.h"', "",
         "/* BT_UUID_128_ENCODE puts the bytes in air order (low byte first). */",
         f"static const struct bt_uuid_128 {p}_serv_uuid = BT_UUID_INIT_128(\n\t{enc(d['u'])});"]
    for c in chars:
        s.append(f"static const struct bt_uuid_128 {p}_{c['n']['snake']}_uuid = BT_UUID_INIT_128(\n\t{enc(c['u'])});")
    s.append("")
    for c in chars:
        s.append(f"static uint8_t {p}_{c['n']['snake']}_val[{U}_{c['n']['upper']}_LEN];")
    s += ["", f"struct {p}_chr {{", "\tuint8_t id;", "\tuint16_t len;", "\tuint8_t *val;", "};", "",
          f"static struct {p}_chr {p}_chrs[] = {{"]
    for c in chars:
        C = f"{U}_{c['n']['upper']}"
        s.append(f"\t{{ {C}_ID, {C}_LEN, {p}_{c['n']['snake']}_val }},")
    s += ["};", "", f"static {p}_change_cb_t {p}_change_cb;", "",
          f"static ssize_t {p}_read(struct bt_conn *conn, const struct bt_gatt_attr *attr,",
          "\t\t\tvoid *buf, uint16_t len, uint16_t offset)", "{",
          f"\tconst struct {p}_chr *c = attr->user_data;", "",
          "\treturn bt_gatt_attr_read(conn, attr, buf, len, offset, c->val, c->len);", "}", ""]
    if any(c["writable"] for c in chars):
        s += [f"static ssize_t {p}_write(struct bt_conn *conn, const struct bt_gatt_attr *attr,",
              "\t\t\t const void *buf, uint16_t len, uint16_t offset, uint8_t flags)", "{",
              f"\tconst struct {p}_chr *c = attr->user_data;", "",
              "\tif (offset != 0) {", "\t\treturn BT_GATT_ERR(BT_ATT_ERR_INVALID_OFFSET);", "\t}",
              "\tif (len != c->len) {", "\t\treturn BT_GATT_ERR(BT_ATT_ERR_INVALID_ATTRIBUTE_LEN);", "\t}",
              "\tif (flags & BT_GATT_WRITE_FLAG_PREPARE) {", "\t\treturn 0;", "\t}",
              "\tmemcpy(c->val, buf, len);", f"\tif ({p}_change_cb) {{", f"\t\t{p}_change_cb(conn, c->id, len, c->val);",
              "\t}", "\treturn len;", "}", ""]
    zp = {"read": "BT_GATT_CHRC_READ", "write": "BT_GATT_CHRC_WRITE", "write-no-response": "BT_GATT_CHRC_WRITE_WITHOUT_RESP",
          "notify": "BT_GATT_CHRC_NOTIFY", "indicate": "BT_GATT_CHRC_INDICATE"}
    entries = [f"\tBT_GATT_PRIMARY_SERVICE(&{p}_serv_uuid)"]
    idx = 1  # attribute index in the service: 0 is the primary service declaration
    for c in chars:
        k = c["n"]["snake"]
        perm = " | ".join(x for x in ["BT_GATT_PERM_READ" if "read" in c["properties"] else "",
                                      "BT_GATT_PERM_WRITE" if c["writable"] else ""] if x) or "BT_GATT_PERM_NONE"
        props = " | ".join(zp[x] for x in PROPS if x in c["properties"])
        entries.append(f"\tBT_GATT_CHARACTERISTIC(&{p}_{k}_uuid.uuid, {props},\n\t\t\t       {perm}, {p}_read, "
                       f"{p + '_write' if c['writable'] else 'NULL'}, &{p}_chrs[{c['id']}])")
        c["zidx"] = idx + 1  # the value attribute follows the declaration
        idx += 2
        if c["cccd"]:
            entries.append("\tBT_GATT_CCC(NULL, BT_GATT_PERM_READ | BT_GATT_PERM_WRITE)")
            idx += 1
        if "description" in c:
            entries.append(f'\tBT_GATT_CUD("{c["description"]}", BT_GATT_PERM_READ)')
            idx += 1
    s += [f"BT_GATT_SERVICE_DEFINE({p}_svc,", ",\n".join(entries) + ");", "",
          f"void {p}_service_init({p}_change_cb_t cb)", "{", f"\t{p}_change_cb = cb;", "}"]
    for c in chars:
        k, C, v = c["n"]["snake"], f"{U}_{c['n']['upper']}", f"{p}_{c['n']['snake']}_val"
        s += ["", f"int {p}_service_set_{k}(const void *value, uint16_t len)", "{",
              f"\tif (len != {C}_LEN) {{", "\t\treturn -EINVAL;", "\t}", f"\tmemcpy({v}, value, len);", "\treturn 0;", "}", "",
              f"int {p}_service_get_{k}(void *value, uint16_t *len)", "{",
              f"\tif (*len < {C}_LEN) {{", "\t\treturn -EINVAL;", "\t}", f"\tmemcpy(value, {v}, {C}_LEN);",
              f"\t*len = {C}_LEN;", "\treturn 0;", "}"]
        if "notify" in c["properties"]:
            s += ["", f"int {p}_service_notify_{k}(void)", "{",
                  f"\treturn bt_gatt_notify(NULL, &{p}_svc.attrs[{c['zidx']}], {v}, {C}_LEN);", "}"]
        if "indicate" in c["properties"]:
            s += ["", f"static struct bt_gatt_indicate_params {p}_{k}_ind;", "",
                  f"int {p}_service_indicate_{k}(void)", "{",
                  f"\t{p}_{k}_ind = (struct bt_gatt_indicate_params){{",
                  f"\t\t.attr = &{p}_svc.attrs[{c['zidx']}], .data = {v}, .len = {C}_LEN,", "\t};",
                  f"\treturn bt_gatt_indicate(NULL, &{p}_{k}_ind);", "}"]
    s.append("")
    return "\n".join(h), "\n".join(s)


def code_lines(text):
    """Lines that are not blank and not comment-only, the count used in portability/driver-layering.md."""
    out, in_c = 0, False
    for line in text.splitlines():
        t = line.strip()
        if in_c:
            if "*/" in t:
                in_c = False
                t = t.split("*/", 1)[1].strip()
            else:
                continue
        if t.startswith("/*"):
            if "*/" not in t:
                in_c = True
                continue
            t = t.split("*/", 1)[1].strip()
        if t and not t.startswith("//"):
            out += 1
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("service", help="service description, JSON (see service.schema.md)")
    ap.add_argument("--target", required=True, choices=["ti-ble5stack", "ti-f3", "zephyr"])
    ap.add_argument("--out", required=True, help="folder for <name>_service.c and .h")
    a = ap.parse_args()
    d = load(a.service)
    name = pathlib.Path(a.service).name
    h, c = zephyr(d, name) if a.target == "zephyr" else ti(d, name, f3=(a.target == "ti-f3"))
    out = pathlib.Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    for ext, text in (("h", h), ("c", c)):
        f = out / f"{d['n']['snake']}_service.{ext}"
        f.write_text(text)
        print(f"wrote {f} ({len(text.splitlines())} lines, {code_lines(text)} code lines)")


if __name__ == "__main__":
    main()
