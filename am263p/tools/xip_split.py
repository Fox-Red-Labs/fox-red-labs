#!/usr/bin/env python3
"""Split an LP-AM263P build into what goes in flash and what the debugger loads into RAM.
xip_split.py <app.out> <blob.h> <ram.out> [--erase-len N]
  blob.h : the sections linked at 0x60000000..0x6FFFFFFF as one image from the lowest such address, gaps 0xFF,
           with XIP_OFFSET (flash offset), BLOB_LEN and ERASE_LEN, for bench/xip/flasher/xip_flasher.c
  ram.out: app.out with those sections removed (tiarmobjcopy), so the RAM load never writes the flash window
With --erase-only OFFSET LEN it writes a blob.h that makes the flasher erase that range and check it reads 0xFF.
With --restore-0x80000 BACKUP.bin it writes a blob.h holding the backup's 128 kB block at 0x80000 (the block TI's flash
driver can rewrite when PHY tuning fails); the flasher writes it back, the only write it allows below 1 MB.
Prints: SPLIT offset 0x.. len N sections a,b,c  (or ERASE offset len)"""
import struct, subprocess, sys
OBJCOPY = "/Applications/ti/ti-cgt-armllvm_release/bin/tiarmobjcopy"
LO, HI = 0x60000000, 0x70000000

def sections(path):
    d = open(path, "rb").read()
    assert d[:4] == b"\x7fELF" and d[4] == 1 and d[5] == 1, "32-bit little-endian ELF expected"
    shoff, = struct.unpack_from("<I", d, 0x20); shentsize, shnum, shstrndx = struct.unpack_from("<HHH", d, 0x2E)
    hdr = [struct.unpack_from("<IIIIIIIIII", d, shoff + i * shentsize) for i in range(shnum)]
    stro = hdr[shstrndx][4]
    out = []
    for h in hdr:
        name = d[stro + h[0]:d.index(b"\0", stro + h[0])].decode()
        typ, flags, addr, off, size = h[1], h[2], h[3], h[4], h[5]
        if (flags & 2) and size and LO <= addr < HI:          # SHF_ALLOC, in the flash window
            out.append((name, addr, d[off:off + size] if typ != 8 else b"\0" * size))
    return out

def write_h(path, off, blob, erase_len):
    with open(path, "w") as f:
        f.write("/* generated by am263p/tools/xip_split.py; do not edit */\n#include <stdint.h>\n")
        f.write(f"#define XIP_OFFSET (0x{off:x}U)\n#define BLOB_LEN ({len(blob)}U)\n#define ERASE_LEN ({erase_len}U)\n")
        f.write("const uint8_t gBlob[%d] __attribute__((aligned(64))) = {\n" % max(len(blob), 1))
        b = blob or b"\0"
        for i in range(0, len(b), 24):
            f.write(",".join(str(x) for x in b[i:i + 24]) + ",\n")
        f.write("};\n")

if __name__ == "__main__":
    if sys.argv[1] == "--restore-0x80000":
        img = open(sys.argv[2], "rb").read()[0x80000:0xA0000]
        assert len(img) == 0x20000, "backup too short"
        write_h(sys.argv[3], 0x80000, img, 0)
        with open(sys.argv[3], "a") as f: f.write("#define XIP_RESTORE_0X80000 1\n")
        print(f"RESTORE offset 0x80000 len {len(img)} from {sys.argv[2]}"); sys.exit(0)
    if sys.argv[1] == "--erase-only":
        off, ln = int(sys.argv[2], 0), int(sys.argv[3], 0)
        write_h(sys.argv[4], off, b"", ln); print(f"ERASE offset 0x{off:x} len {ln}"); sys.exit(0)
    app, hpath, ram = sys.argv[1:4]
    secs = sections(app)
    if not secs:
        sys.exit("no sections in the flash window")
    base = min(a for _, a, _ in secs); end = max(a + len(b) for _, a, b in secs)
    img = bytearray(b"\xff" * (end - base))
    for _, a, b in secs:
        img[a - base:a - base + len(b)] = b
    write_h(hpath, base - LO, bytes(img), 0)
    subprocess.run([OBJCOPY] + [f"--remove-section={n}" for n, _, _ in secs] + [app, ram], check=True)
    # objcopy keeps the PT_LOAD header for the flash window (with file bytes); null it so no loader writes there
    d = bytearray(open(ram, "rb").read())
    phoff, = struct.unpack_from("<I", d, 0x1C); phentsize, phnum = struct.unpack_from("<HH", d, 0x2A)
    for i in range(phnum):
        p = phoff + i * phentsize
        typ, _, vaddr, paddr = struct.unpack_from("<IIII", d, p)
        if typ == 1 and (LO <= vaddr < HI or LO <= paddr < HI):
            struct.pack_into("<I", d, p, 0)                       # PT_NULL
    open(ram, "wb").write(d)
    print(f"SPLIT offset 0x{base - LO:x} len {len(img)} sections {','.join(n for n, _, _ in secs)}")
