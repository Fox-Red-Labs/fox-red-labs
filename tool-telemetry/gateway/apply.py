#!/usr/bin/env python3
"""Turn a copy of TI's network_terminal demo (CC35X1) into the tool-telemetry gateway.
   python3 apply.py <copy of the network_terminal folder>
Adds tt_gateway.c and the shared codec, starts the gateway just before the terminal prompt, and adds the two files to
the makefile. The hub's Wi-Fi password comes from TTGW_AP_PASS (build.sh makes a random one per hub and keeps it outside the repo).
Optional site uplink from the environment: SITE_SSID and WIFI_ENV (a file with WIFI_PASSWORD=...); they go
into this copy only. Every edit must match exactly once or the script stops."""
import os
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PROTO = HERE.parent / "proto"
root = Path(sys.argv[1])


def edit(path, old, new, count=1):
    t = path.read_text()
    if t.count(old) != count:
        sys.exit(f"{path.name}: expected {count} match of {old!r}, found {t.count(old)}")
    path.write_text(t.replace(old, new))


FD = HERE.parent.parent / "portability" / "fielddata" / "c"
for f in (HERE / "tt_gateway.c", PROTO / "tt_proto.c", PROTO / "tt_proto.h", FD / "fd_frame.c", FD / "fd_frame.h"):
    shutil.copy2(f, root / f.name)
if not (root / "tt_app.h").exists():
    sys.exit("tt_app.h missing: run app/embed.py first (build.sh does)")

nt = root / "network_terminal.c"
edit(nt, "    RetVal = cmd_prompt(NULL);\n",
     "    extern void TTGW_start(void);\n    TTGW_start();\n    RetVal = cmd_prompt(NULL);\n")

mk = root / "freertos" / "ticlang" / "makefile"
edit(mk, "network_terminal.obj date_time_service.obj", "network_terminal.obj tt_gateway.obj tt_proto.obj fd_frame.obj date_time_service.obj")
ap_pass = os.environ.get("TTGW_AP_PASS", "")
if len(ap_pass) < 8:
    sys.exit("TTGW_AP_PASS must be 8 or more characters (build.sh sets it)")
def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


lines = ["/* Generated by apply.py into the build copy only. Never commit. */", "#define TTGW_AP_PASS " + cstr(ap_pass)]
ssid = os.environ.get("SITE_SSID")
if ssid:
    envf = os.environ.get("WIFI_ENV", os.path.expanduser("~/.config/frl/home-wifi.env"))
    pw = [l.split("=", 1)[1].strip().strip("\"'") for l in open(envf) if l.startswith("WIFI_PASSWORD=")][0]
    lines += ["#define TTGW_SITE_SSID " + cstr(ssid), "#define TTGW_SITE_PASS " + cstr(pw)]
ctrl = os.environ.get("TTGW_CTRL_TOKEN", "")   # SECURE=1 builds: needed on POST /api/model, /api/cmd and /api/lease
if ctrl:
    if len(ctrl) < 12:
        sys.exit("TTGW_CTRL_TOKEN must be 12 or more characters (build.sh sets it)")
    lines += ["#define TTGW_CTRL_TOKEN " + cstr(ctrl)]
lat, lon = os.environ.get("SITE_LAT"), os.environ.get("SITE_LON")   # where this hub stands, for the dashboards
if lat and lon:
    lines += ["#define TTGW_SITE_JSON " + cstr(',"site":{"lat":%.3f,"lon":%.3f}' % (float(lat), float(lon)))]
up = os.environ.get("UPLINK_URL")      # the hub posts its log here by itself, e.g. http://<home base address>:8090/api/ingest
if up:
    if not up.startswith("http://") or "/" not in up[7:]:
        sys.exit("UPLINK_URL must look like http://<ip address>:<port>/api/ingest (no DNS on the hub yet)")
    lines += ["#define TTGW_UPLINK_URL " + cstr(up), "#define TTGW_UPLINK_TOKEN " + cstr(os.environ.get("UPLINK_TOKEN", ""))]
(root / "tt_secrets.h").write_text("\n".join(lines) + "\n")
defs = ""
rule = "{o}: ../../{c} $(SYSCFG_H_FILES)\n\t@ echo Building $@\n\t$(V) $(CC) $(CFLAGS){d} -c $< -o $@\n\n"
edit(mk, "date_time_service.obj: ../../date_time_service.c",
     rule.format(o="tt_gateway.obj", c="tt_gateway.c", d=defs) + rule.format(o="tt_proto.obj", c="tt_proto.c", d="")
     + rule.format(o="fd_frame.obj", c="fd_frame.c", d="")
     + "date_time_service.obj: ../../date_time_service.c")
print("applied to", root, "(site uplink: %s)" % ("yes" if ssid else "no"))
