#!/usr/bin/env python3
"""Turn a copy of TI's basic_ble example into the tool tag.
   python3 apply.py <copy of the basic_ble example folder>
Adds tooltag.c and the shared codec, calls ToolTag_start() after Peripheral_start(), frees the UART from TI's menu so
the tool MCU can use it, turns on extended advertising, fixes the address (public, so a gateway can follow one tag),
and slows the legacy set to 500 ms. Every edit must match exactly once or the script stops."""
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PROTO = HERE.parent / "proto"
root = Path(sys.argv[1])


def edit(path, old, new, count=1):
    t = path.read_text()
    if t.count(old) != count:
        sys.exit(f"{path.name}: expected {count} match of {old!r}, found {t.count(old)}")
    path.write_text(t.replace(old, new))


MODEL = HERE.parent / "ai" / "out"
if not (MODEL / "tt_model.c").exists():
    sys.exit("ai/out/tt_model.c missing: run python3 tool-telemetry/ai/train.py first (build.sh does)")
FD = HERE.parent.parent / "portability" / "fielddata" / "c"
for f in (HERE / "tooltag.c", HERE / "tooltag.h", PROTO / "tt_proto.c", PROTO / "tt_proto.h", PROTO / "tt_mdl.c", PROTO / "tt_mdl.h", MODEL / "tt_model.c",
          MODEL / "tt_model.h", FD / "fd_frame.c", FD / "fd_frame.h"):
    shutil.copy2(f, root / "app" / f.name)

# the fleet signing key for installed models: never in the repository, only in the build copy
import os
keyf = Path(os.environ.get("TT_MODEL_KEY", Path.home() / ".config/frl/tool-telemetry-model.key"))
key = bytes.fromhex(keyf.read_text().strip()) if keyf.exists() else b""
if len(key) != 16:
    sys.exit(f"{keyf}: needs 32 hex digits (build.sh makes one)")
(root / "app" / "tt_key.h").write_text("/* Generated by apply.py into the build copy only. Never commit. */\n"
                                       "static const uint8_t TT_MDL_KEY[16] = { " + ", ".join("0x%02x" % b for b in key) + " };\n")

main = root / "app" / "app_main.c"
edit(main, "#include <app_main.h>\n", '#include <app_main.h>\n#include "tooltag.h"\n')
edit(main, "    status = Peripheral_start();\n    if(status != SUCCESS)\n    {\n        // TODO: Call Error Handler\n    }\n",
     "    status = Peripheral_start();\n    if(status != SUCCESS)\n    {\n        // TODO: Call Error Handler\n    }\n"
     "    status = ToolTag_start();\n    if(status != SUCCESS)\n    {\n        // TODO: Call Error Handler\n    }\n")

cfg = root / "freertos" / "basic_ble.syscfg"
edit(cfg, "var needsDisplay = true;", "var needsDisplay = false;\nvar needsUartNpi = true;")
edit(cfg, 'ble.deviceName = "Basic BLE project";',
     'ble.deviceName = "Tool Tag";\nble.extAdv = true;\nble.addressMode = "ADDRMODE_PUBLIC";\n'
     "ble.advSet1.advParam1.primIntMin = 500;\nble.advSet1.advParam1.primIntMax = 500;")

mk = root / "freertos" / "ticlang" / "makefile"
edit(mk, "app_Profiles_app_simple_gatt.obj ", "app_Profiles_app_simple_gatt.obj app_tooltag.obj app_tt_proto.obj app_tt_mdl.obj app_tt_model.obj app_fd_frame.obj ")
pre = " prebuild" if "\nprebuild:" in mk.read_text() else ""     # the CC2340R5 makefile has a prebuild step, the CC2755P10's does not
rule = "{o}: ../../app/{c} $(SYSCFG_H_FILES)" + pre + "\n\t@ echo Building $@\n\t$(V) $(CC) $(CFLAGS) -c $< -o $@\n\n"
edit(mk, "app_app_main.obj: ../../app/app_main.c",
     rule.format(o="app_tooltag.obj", c="tooltag.c") + rule.format(o="app_tt_proto.obj", c="tt_proto.c")
     + rule.format(o="app_tt_mdl.obj", c="tt_mdl.c") + rule.format(o="app_tt_model.obj", c="tt_model.c") + rule.format(o="app_fd_frame.obj", c="fd_frame.c")
     + "app_app_main.obj: ../../app/app_main.c")
print("applied to", root)
