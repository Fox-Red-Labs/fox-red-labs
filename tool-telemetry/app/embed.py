#!/usr/bin/env python3
"""Gzip the phone app into a C header for the gateway firmware.
   python3 embed.py <index.html> <out tt_app.h>
mtime is fixed so the same page gives the same bytes."""
import gzip
import sys

src, dst = sys.argv[1], sys.argv[2]
raw = open(src, "rb").read()
# the app schemas (portability/fielddata/apps/*.json) go into the page, so a hub with no internet can decode every app
import glob, json, os
apps_dir = os.path.join(os.path.dirname(os.path.abspath(src)), "..", "..", "portability", "fielddata", "apps")
apps = [json.load(open(p)) for p in sorted(glob.glob(os.path.join(apps_dir, "*.json")))]
raw = raw.replace(b"/*APPS*/[]", json.dumps(apps, separators=(",", ":")).encode())
gz = gzip.compress(raw, compresslevel=9, mtime=0)
rows = [", ".join("0x%02x" % b for b in gz[i:i + 16]) for i in range(0, len(gz), 16)]
open(dst, "w").write("/* Generated by tool-telemetry/app/embed.py from index.html (%d bytes, gzip %d). Do not edit. */\n"
                     "static const unsigned char tt_app_gz[%d] = {\n  %s\n};\n" % (len(raw), len(gz), len(gz), ",\n  ".join(rows)))
print("%s: %d bytes, gzip %d" % (dst, len(raw), len(gz)))
