#!/usr/bin/env python3
"""Write core/frl_sintab.h: sin(2 pi i/256) for i = 0..256 as Q24 (int32). Run once; the output is checked in."""
import math, pathlib
out = pathlib.Path(__file__).resolve().parents[1] / "core" / "frl_sintab.h"
v = [round(math.sin(2 * math.pi * i / 256) * (1 << 24)) for i in range(257)]
rows = [", ".join(str(x) for x in v[i:i + 8]) for i in range(0, 257, 8)]
out.write_text("/* generated by tests/gen_sintab.py: sin(2 pi i/256), i = 0..256, Q24. Do not edit. */\n"
               "static const int32_t frl_sintab_q24[257] = {\n\t" + ",\n\t".join(rows) + "\n};\n")
print(out)
