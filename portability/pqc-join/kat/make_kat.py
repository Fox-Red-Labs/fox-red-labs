#!/usr/bin/env python3
"""Pick the ML-KEM-768 known-answer tests out of NIST's ACVP-Server files and write them as
kat/nist_mlkem768_kat.json (small, kept in the repo) and core/pqc_kat_data.h (C arrays).

  python3 make_kat.py <ML-KEM-keyGen-FIPS203/internalProjection.json> <ML-KEM-encapDecap-FIPS203/internalProjection.json>

Tests used: keyGen ML-KEM-768 tcId 26 (the vector TI's pqc_mlkem_768_keygen example carries), the first
ML-KEM-768 encapsulation test, the first ML-KEM-768 decapsulation test. Source and checksums: kat/SOURCE.md."""
import hashlib, json, sys
from pathlib import Path

here = Path(__file__).resolve().parent
kg_path, ed_path = sys.argv[1], sys.argv[2]
kg, ed = json.load(open(kg_path)), json.load(open(ed_path))

def group(doc, param, fn=None):
    for g in doc["testGroups"]:
        if g["parameterSet"] == param and (fn is None or g.get("function") == fn):
            return g
    raise SystemExit("group not found")

k = next(t for t in group(kg, "ML-KEM-768")["tests"] if t["tcId"] == 26)
e = group(ed, "ML-KEM-768", "encapsulation")["tests"][0]
d = group(ed, "ML-KEM-768", "decapsulation")["tests"][0]
out = {
    "keygen": {"tcId": k["tcId"], "d": k["d"], "z": k["z"], "ek": k["ek"], "dk": k["dk"]},
    "encaps": {"tcId": e["tcId"], "ek": e["ek"], "m": e["m"], "c": e["c"], "k": e["k"]},
    "decaps": {"tcId": d["tcId"], "dk": d["dk"], "c": d["c"], "k": d["k"]},
}
out["_source"] = {"files": {Path(p).parent.name: hashlib.sha256(open(p, "rb").read()).hexdigest() for p in (kg_path, ed_path)}}
(here / "nist_mlkem768_kat.json").write_text(json.dumps(out, indent=1) + "\n")

def arr(name, hexs):
    b = bytes.fromhex(hexs)
    rows = ["    " + ", ".join("0x%02x" % x for x in b[i:i + 12]) for i in range(0, len(b), 12)]
    return "static const uint8_t %s[%d] = {\n%s};\n" % (name, len(b), ",\n".join(rows))

h = ["/* Generated by kat/make_kat.py from NIST ACVP-Server vectors. Do not edit. */",
     "#ifndef PQC_KAT_DATA_H", "#define PQC_KAT_DATA_H", "#include <stdint.h>", ""]
for sec, names in (("keygen", ("d", "z", "ek", "dk")), ("encaps", ("ek", "m", "c", "k")), ("decaps", ("dk", "c", "k"))):
    for n in names:
        h.append(arr("kat_%s_%s" % (sec, n), out[sec][n].lower()))
h.append("#endif")
(here.parent / "core" / "pqc_kat_data.h").write_text("\n".join(h) + "\n")
print("tcIds", k["tcId"], e["tcId"], d["tcId"])
