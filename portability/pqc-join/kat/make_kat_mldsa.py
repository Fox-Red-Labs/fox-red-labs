#!/usr/bin/env python3
"""Pick the ML-DSA-44 known-answer tests out of NIST's ACVP-Server files and write them as
kat/nist_mldsa44_kat.json (small, kept in the repo) and core/pqc_mldsa_kat_data.h (C arrays).

  python3 make_kat_mldsa.py <ML-DSA-keyGen-FIPS204/internalProjection.json> \
      <ML-DSA-sigGen-FIPS204/internalProjection.json> <ML-DSA-sigVer-FIPS204/internalProjection.json>

Tests used, all ML-DSA-44 with the external (pure) interface where there is a choice: key generation
tcId 1; from the hedged and the deterministic signing groups, the test with the shortest message;
from the verification group, the shortest-message test NIST marks valid and the shortest it marks
invalid. Source and checksums: kat/SOURCE.md."""
import hashlib, json, sys
from pathlib import Path

here = Path(__file__).resolve().parent
kg_path, sg_path, sv_path = sys.argv[1], sys.argv[2], sys.argv[3]
kg, sg, sv = (json.load(open(p)) for p in (kg_path, sg_path, sv_path))

def group(doc, **want):
    for g in doc["testGroups"]:
        if g["parameterSet"] == "ML-DSA-44" and all(g.get(k) == v for k, v in want.items()):
            return g
    raise SystemExit("group not found: %r" % want)

def shortest(tests):
    return min(tests, key=lambda t: (len(t["message"]), t["tcId"]))

k = next(t for t in group(kg)["tests"] if t["tcId"] == 1)
sh = shortest(group(sg, deterministic=False, signatureInterface="external", preHash="pure")["tests"])
sd = shortest(group(sg, deterministic=True, signatureInterface="external", preHash="pure")["tests"])
vg = group(sv, signatureInterface="external", preHash="pure")["tests"]
vy = shortest([t for t in vg if t["testPassed"]])
vn = shortest([t for t in vg if not t["testPassed"]])
pick = lambda t, ks: dict({"tcId": t["tcId"]}, **{x: t[x] for x in ks if x in t})
out = {
    "keygen": pick(k, ("seed", "pk", "sk")),
    "sign_hedged": pick(sh, ("sk", "message", "context", "rnd", "signature")),
    "sign_deterministic": pick(sd, ("sk", "message", "context", "signature")),
    "verify_valid": pick(vy, ("pk", "message", "context", "signature", "reason")),
    "verify_invalid": pick(vn, ("pk", "message", "context", "signature", "reason")),
}
out["_source"] = {"files": {Path(p).parent.name: hashlib.sha256(open(p, "rb").read()).hexdigest() for p in (kg_path, sg_path, sv_path)}}
(here / "nist_mldsa44_kat.json").write_text(json.dumps(out, indent=1) + "\n")

def arr(name, hexs):
    b = bytes.fromhex(hexs)
    if not b:
        return "static const uint8_t %s[1] = {0};\n#define %s_LEN 0\n" % (name, name.upper())
    rows = ["    " + ", ".join("0x%02x" % x for x in b[i:i + 12]) for i in range(0, len(b), 12)]
    return "static const uint8_t %s[%d] = {\n%s};\n#define %s_LEN %d\n" % (name, len(b), ",\n".join(rows), name.upper(), len(b))

h = ["/* Generated by kat/make_kat_mldsa.py from NIST ACVP-Server vectors. Do not edit. */",
     "#ifndef PQC_MLDSA_KAT_DATA_H", "#define PQC_MLDSA_KAT_DATA_H", "#include <stdint.h>", ""]
for sec in ("keygen", "sign_hedged", "sign_deterministic", "verify_valid", "verify_invalid"):
    h.append("/* %s: NIST ACVP tcId %d */" % (sec, out[sec]["tcId"]))
    for n, v in out[sec].items():
        if n in ("tcId", "reason"):
            continue
        h.append(arr("kd_%s_%s" % (sec, n), v.lower()))
h.append("#endif")
(here.parent / "core" / "pqc_mldsa_kat_data.h").write_text("\n".join(h) + "\n")
print({s: (out[s]["tcId"], out[s].get("reason")) for s in out if s != "_source"})
