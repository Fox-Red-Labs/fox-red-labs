/*
 * Reference vectors for the wire packer: TI's own structs, built the way trx_host.c builds them, on a
 * byte-addressed host (Mac, clang, -fshort-enums as the Arm builds of the driver use). Writes vectors.h.
 * Usage: ref_gen <driver_first_txn.txt> > vectors.h
 *   driver_first_txn.txt: the bytes TI's unmodified driver sent first on this host (from the fake-radio bench).
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <stdint.h>
#include "host/trx_host.h"
#include "rcl_settings_wisun.h"
#include "hal/platform_util.h"
#include "scenario.h"
/* same definition as host/private/trx_host_private.h */
#define CLOSEST_WORD_BOUNDARY_BYTES(len) (((len) + 3) & ~0x03)
#define PADDING_REQUIRED(len) (CLOSEST_WORD_BOUNDARY_BYTES(len) - (len))

_Static_assert(sizeof(TRX_Request_CommandStore) == 48, "cmd store len");
_Static_assert(sizeof(TRX_Request_DeviceConfigStore) == 14, "devcfg len");
_Static_assert(DIO2_HIGH_PA == SC_DIO2 && DIO3_LOW_PA_AND_LNA == SC_DIO3 && DIO0_UNCHANGED == SC_DIO0, "dio codes");
_Static_assert(TRX_PHY_FEATURE_FSK_MODE_2B_WISUN == SC_PHY_MASK, "phy mask");

void ref_noop(void){}
static void emit(const char *name, const uint8_t *b, unsigned n)
{
    printf("static const unsigned char %s[] = {", name);
    for (unsigned i = 0; i < n; i++) printf("%s0x%02X", i ? (i % 16 ? "," : ",\n  ") : "\n  ", b[i]);
    printf("\n};\n#define %s_LEN %uu\n", name, n);
}
static uint32_t fnv(const uint8_t *b, unsigned n)
{
    uint32_t h = 2166136261u;
    for (unsigned i = 0; i < n; i++) { h ^= b[i]; h *= 16777619u; }
    return h;
}
/* driver: TRX_Host_storeConfig copies table bytes straight out of the uint32 array */
static unsigned table_octets(const uint32_t *t, unsigned words, uint8_t *out) { memcpy(out, t, 4u * words); return 4u * words; }

int main(int argc, char **argv)
{
    uint8_t b[256]; uint8_t tab[4096];
    printf("/* Generated by ref_gen.c from TI's structs (-fshort-enums, byte-addressed host). Do not edit. */\n");

    memset(b, 0, sizeof b);
    { TRX_Request_ConfigList *r = (TRX_Request_ConfigList *)b; r->header.request = Req_CONFIG_LIST; r->header.len = sizeof *r; emit("V_CONFIG_LIST", b, sizeof *r); }
    memset(b, 0, sizeof b);
    { TRX_Request_NvErase *r = (TRX_Request_NvErase *)b; r->header.request = Req_NV_ERASE; r->header.len = sizeof *r; emit("V_NV_ERASE", b, sizeof *r); }
    memset(b, 0, sizeof b);
    { TRX_Request_Ping *r = (TRX_Request_Ping *)b; r->header.request = Req_PING; r->header.len = sizeof *r; r->pingData = 0xA5; emit("V_PING", b, sizeof *r); }
    memset(b, 0, sizeof b);
    TRX_Request_DeviceConfigStore dcs; memset(&dcs, 0, sizeof dcs);
    {
        dcs.header.request = Req_DEVICE_CONFIG_STORE; dcs.header.len = sizeof dcs;
        dcs.data.dioConfig.dio0 = SC_DIO0; dcs.data.dioConfig.dio2 = SC_DIO2; dcs.data.dioConfig.dio3 = SC_DIO3;
        dcs.data.dioConfig.dio4 = SC_DIO4; dcs.data.dioConfig.dio5 = SC_DIO5; dcs.data.dioConfig.dio6 = SC_DIO6;
        dcs.data.dioConfig.dio7 = SC_DIO7;
        dcs.data.clockConfig = SC_CLOCK; dcs.data.powerMode.dwellTimeUs = SC_DWELL; dcs.data.powerMode.powerPolicy = SC_POLICY;
        dcs.data.rfMode = SC_RFMODE;
        memcpy(b, &dcs, sizeof dcs); emit("V_DEVCFG", b, sizeof dcs);
    }
    /* config store, two fragments of the frontend table */
    unsigned fe_words = LRF_frontendRegConfig_wisun_byteCount / 4u;
    unsigned fe = table_octets(LRF_frontendRegConfig_wisun, fe_words, tab);
    printf("#define SC_FE_WORDS %uu\n", fe_words);
    printf("#define SC_FE_FNV 0x%08Xu\n", fnv(tab, fe));
    for (int part = 0; part < 2; part++) {
        unsigned off = part ? fe - SC_FRAG2_LEN : 0, len = part ? SC_FRAG2_LEN : SC_FRAG1_LEN;
        memset(b, 0, sizeof b);
        TRX_Request_ConfigStore *r = (TRX_Request_ConfigStore *)b;
        memcpy(r->data, tab + off, len);
        r->header.request = Req_CONFIG_STORE; r->header.len = sizeof *r + len;
        r->start = (off == 0); r->md = part ? 0 : 1; r->config_id = TRX_CONFIG_ID_FRONTEND; r->reference = SC_FE_REF;
        emit(part ? "V_CFG_STORE_LAST" : "V_CFG_STORE_FIRST", b, sizeof *r + len);
        printf("#define V_CFG_STORE_%s_OFF %uu\n", part ? "LAST" : "FIRST", off);
    }
    memset(b, 0, sizeof b);
    { TRX_Request_ConfigPersist *r = (TRX_Request_ConfigPersist *)b; r->header.request = Req_CONFIG_PERSIST; r->header.len = sizeof *r; r->config_id = 1; emit("V_CFG_PERSIST", b, sizeof *r); }
    /* main table: hash only (1.8 kB) */
    unsigned mw = LRF_mainRegConfig_wisun_byteCount / 4u;
    unsigned mn = table_octets(LRF_mainRegConfig_wisun, mw, tab);
    printf("#define SC_MAIN_WORDS %uu\n#define SC_MAIN_FNV 0x%08Xu\n", mw, fnv(tab, mn));
    /* command store: TX */
    {
        TRX_Request_CommandStore cmd; memset(&cmd, 0, sizeof cmd);
        cmd.slot = SC_CMD_SLOT; cmd.cmd_id = TRX_RadioCommand_Transmit; cmd.trigger = Command_Trigger_Immediate;
        cmd.conflict_policy = TRX_ConflictPolicy_AlwaysInterrupt;
        cmd.params.tx.phy0.config_id = SC_PHY_CFGID; cmd.params.tx.phy0.option_mask = SC_PHY_MASK;
        cmd.params.tx.pa = TRX_TxPa_High; cmd.params.tx.stream_id = SC_STREAM_ID; cmd.params.tx.frequency = SC_FREQ_KHZ;
        cmd.params.tx.modem = TRX_RadioCommand_Modem_FSK;
        cmd.params.tx.power = TRX_txPowerLevelsHigh_wisun.powerLevels[TRX_txPowerLevelsHigh_wisun.numEntries - 1];
        /* also the branch / schedule fields, so every field byte is exercised */
        cmd.slot_on_true = 3; cmd.enable_on_true = 1; cmd.slot_on_false = 5; cmd.enable_on_false = 0;
        cmd.slot_on_compare = 7; cmd.enable_on_compare = 2; cmd.next_status_compare = -2;
        cmd.allow_delay = 1; cmd.chain_trigger = 10; cmd.chain_conflict_policy = 2; cmd.chain_allow_delay = 1;
        cmd.trigger_param = 0x11223344u; cmd.chain_trig_param = 0x55667788u;
        cmd.params.tx.phy1.option_mask = 0x1234; cmd.params.tx.phy1.config_id = 9;
        cmd.params.tx.phy2.option_mask = 0xBEEF; cmd.params.tx.phy2.config_id = 15;
        cmd.header.request = Req_CMD_STORE; cmd.header.len = sizeof cmd;
        memset(b, 0, sizeof b); memcpy(b, &cmd, sizeof cmd); emit("V_CMD_STORE", b, sizeof cmd);
        printf("#define SC_PWR_RAW 0x%02Xu\n", (unsigned)(uint8_t)cmd.params.tx.power.rawValue);
        if (cmd.params.tx.frequency != SC_FREQ_KHZ) return 1;
    }
    memset(b, 0, sizeof b);
    { TRX_Request_CommandSubmit *r = (TRX_Request_CommandSubmit *)b; r->header.request = Req_CMD_SUBMIT; r->header.len = sizeof *r; r->slot = 4; emit("V_CMD_SUBMIT", b, sizeof *r); }
    memset(b, 0, sizeof b);
    { TRX_Request_CommandStop *r = (TRX_Request_CommandStop *)b; r->header.request = Req_CMD_STOP; r->header.len = sizeof *r; r->slot = 2; r->stop_type = TRX_Command_StopType_Graceful; emit("V_CMD_STOP", b, sizeof *r); }
    /* payload header + stream store */
    uint8_t pkt[4 + SC_PAYLOAD_LEN];
    memset(pkt, 0, sizeof pkt);
    { TRX_PayloadHeader_SunFSK *h = (TRX_PayloadHeader_SunFSK *)pkt; h->length = SC_PAYLOAD_LEN; h->modulation = TRX_PayloadHeader_Modulation_FSK; h->whitening = 1; h->fcs_mode = 1; h->newPhyId = 0x2C;
      emit("V_PAYLOAD_HDR", pkt, 4); }
    for (unsigned i = 0; i < SC_PAYLOAD_LEN; i++) pkt[4 + i] = (uint8_t)SC_PAY_BYTE(i);
    memset(b, 0, sizeof b);
    { TRX_Request_StreamStore *r = (TRX_Request_StreamStore *)b; memcpy(r->data, pkt, sizeof pkt);
      r->header.request = Req_STREAM_STORE; r->header.len = sizeof *r + sizeof pkt; r->stream_id = 5; r->start = 1; r->md = 0; r->retention = Stream_Retention_Flush_Streaming;
      emit("V_STREAM_STORE", b, sizeof *r + sizeof pkt); }
    /* one transaction holding DEVICE_CONFIG_STORE then NV_ERASE: the driver pads each request to 4 and the payload to 4 */
    {
        uint8_t t[140]; memset(t, 0, sizeof t);
        TRX_TransactionHeader *th = (TRX_TransactionHeader *)t;
        unsigned idx = 0;
        memcpy(t + 4 + idx, &dcs, sizeof dcs); idx += sizeof dcs; idx += PADDING_REQUIRED(idx);
        TRX_Request_NvErase nv; nv.header.request = Req_NV_ERASE; nv.header.len = sizeof nv;
        memcpy(t + 4 + idx, &nv, sizeof nv); idx += sizeof nv;
        idx += PADDING_REQUIRED(idx);
        th->host.len = idx; th->host.tid_tx = 2; th->host.tid_ack = 1;
        uint16_t crc = Plat_Util_computeCRC(t, 4 + idx);
        t[4 + idx] = crc >> 8; t[4 + idx + 1] = crc & 0xFF;
        emit("V_TXN_DEVCFG_NVERASE", t, 4 + idx + 2);
    }
    /* the real driver's first transaction (unmodified TI driver, fake radio) */
    if (argc > 1) {
        FILE *f = fopen(argv[1], "r"); uint8_t t[64]; unsigned n = 0, v;
        if (!f) return 2;
        while (n < sizeof t && fscanf(f, "%x", &v) == 1) t[n++] = (uint8_t)v;
        fclose(f); emit("V_DRIVER_TXN1", t, n);
    }
    /* radio to host: a transaction carrying LAST_STATUS (config list answer) and CMD_STATUS */
    {
        uint8_t t[64]; memset(t, 0, sizeof t);
        TRX_TransactionHeader *th = (TRX_TransactionHeader *)t;
        unsigned idx = 0;
        TRX_Request_LastStatus ls; memset(&ls, 0, sizeof ls);
        ls.header.request = Req_LAST_STATUS; ls.header.len = sizeof ls + 1; ls.req = Req_CONFIG_LIST; ls.strobe = 0; ls.tid = 3; ls.status = TRX_STATUS_SUCCESS;
        memcpy(t + 4 + idx, &ls, sizeof ls); t[4 + idx + sizeof ls] = 2; idx += sizeof ls + 1; idx += PADDING_REQUIRED(idx);
        TRX_Request_CommandStatus cs; memset(&cs, 0, sizeof cs);
        cs.header.request = Req_CMD_STATUS; cs.header.len = sizeof cs; cs.status = 0x40; cs.command_id = TRX_RadioCommand_Transmit; cs.slot = 4; cs.chain_action = 1; cs.chain_target = 6;
        memcpy(t + 4 + idx, &cs, sizeof cs); idx += sizeof cs; idx += PADDING_REQUIRED(idx);
        th->trx.free = 12; th->trx.error = 1; th->trx.data_rdy_n = 0; th->trx.chip_rdy_n = 0; th->trx.len = idx; th->trx.tid_tx = 9; th->trx.tid_ack = 2; th->trx.status = 0x80;
        uint16_t crc = Plat_Util_computeCRC(t, 4 + idx);
        t[4 + idx] = crc >> 8; t[4 + idx + 1] = crc & 0xFF;
        emit("V_RX_TXN", t, 4 + idx + 2);
        printf("#define V_RX_FREE %uu\n#define V_RX_ERROR %uu\n#define V_RX_LEN %uu\n#define V_RX_TIDTX %uu\n#define V_RX_TIDACK %uu\n#define V_RX_STATUS %uu\n",
               th->trx.free, th->trx.error, th->trx.len, th->trx.tid_tx, th->trx.tid_ack, th->trx.status);
        TRX_Request_LastStatus *l = (TRX_Request_LastStatus *)(t + 4);
        printf("#define V_LS_REQ %uu\n#define V_LS_TID %uu\n#define V_LS_STATUS %uu\n#define V_LS_PARAM %uu\n#define V_LS_OFF 0u\n", l->req, l->tid, l->status, l->params[0]);
        unsigned co = (sizeof ls + 1) + PADDING_REQUIRED(sizeof ls + 1);
        TRX_Request_CommandStatus *c = (TRX_Request_CommandStatus *)(t + 4 + co);
        printf("#define V_CS_OFF %uu\n#define V_CS_STATUS %uu\n#define V_CS_CMD %uu\n#define V_CS_SLOT %uu\n#define V_CS_CHAIN %uu\n#define V_CS_TARGET %uu\n",
               co, c->status, c->command_id, c->slot, c->chain_action, c->chain_target);
    }
    /* stream descriptor (config list response entry) */
    {
        TRX_StreamDescriptor d; memset(&d, 0, sizeof d); d.stream_id = 37; d.persisted = 1; d.length = 1234; d.reference = 0xCAFEF00Du;
        uint8_t t[8]; memcpy(t, &d, 8); emit("V_STREAM_DESC", t, 8);
    }
    return 0;
}
