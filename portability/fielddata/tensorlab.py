#!/usr/bin/env python3
"""Turn one exported app folder into a TI Tiny ML Tensorlab run: a config YAML and the dataset zip Edge AI Studio's
Model Composer imports. Standard library only.
    python3 portability/fielddata/tensorlab.py <export>/<app> [--device MSPM0G5187] [--model CLS_1k_NPU]
        [--epochs 20] [--lr 0.001] [--batch auto] [--quant 2] [--qat] [--frame N]
Writes <app>/tensorlab/config.yaml and <app>/tensorlab/<app>_field.zip (classes/ and annotations/ at the top).
Keys follow TI's documentation read 2026-10-17 (tool-telemetry/research/open-data-chain-2026-10-17.md, section 4).
The YAML has not been run in Tensorlab here; the first real run is the check."""
import argparse
import json
import os
import zipfile

# TI's documented target_device values; the three with an NPU take the CLS_*_NPU models
DEVICES = ["F28P55", "F28P65", "F29H85", "F29P58", "F29P32", "F2837", "F28004", "F28003", "F280013", "F280015",
           "MSPM0G3507", "MSPM0G3519", "MSPM0G5187", "MSPM33C32", "MSPM33C34", "AM13E2", "AM263", "AM263P", "AM261",
           "CC2755", "CC1352", "CC1354", "CC35X1"]
NPU = {"F28P55", "AM13E2", "MSPM0G5187"}
SIZES = ["100", "500", "1k", "1.2k", "1.5k", "1.9k", "2k", "2.8k", "3.1k", "3.9k", "4k", "4.2k", "5k", "6k", "8k", "13k",
         "20k", "24k", "40k", "55k"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("app_dir", help="an exported app folder, such as field-dataset/presence")
    ap.add_argument("--device", default="MSPM0G5187", choices=DEVICES)
    ap.add_argument("--model", default="CLS_1k_NPU", help="CLS_<size>_NPU, size one of " + ", ".join(SIZES))
    ap.add_argument("--epochs", type=int, default=20)
    ap.add_argument("--lr", type=float, default=0.001)
    ap.add_argument("--batch", default="auto", help="auto picks about a tenth of the training files' windows, 8 to 256")
    ap.add_argument("--quant", type=int, default=2, choices=(0, 1, 2), help="0 float, 1 PyTorch, 2 TI NPU style")
    ap.add_argument("--qat", action="store_true", help="quantization-aware training instead of post-training")
    ap.add_argument("--frame", type=int, help="samples per frame; default the schema's window")
    a = ap.parse_args()

    od = os.path.abspath(a.app_dir)
    tl = os.path.join(od, "tensorlab")
    apps = {x["name"]: x for x in json.load(open(os.path.join(od, "..", "schema.json")))}
    app = apps[os.path.basename(od)]
    tr = app["training"]
    ch = tr["channels"]
    ts = tr["task"].startswith("timeseries")
    frame = a.frame or tr.get("window") or 4
    stride = tr.get("stride", frame)
    if not os.path.isdir(os.path.join(tl, "classes")):
        raise SystemExit("no tensorlab/classes in %s: run export.py first" % od)

    # check every class file against what Tensorlab needs before anyone uploads it
    problems, rows_per_class, files = [], {}, []
    for lab in sorted(os.listdir(os.path.join(tl, "classes"))):
        for fn in sorted(os.listdir(os.path.join(tl, "classes", lab))):
            rel = "classes/%s/%s" % (lab, fn)
            lines = open(os.path.join(tl, rel)).read().splitlines()
            head, body = lines[0].split(","), lines[1:]
            if head != ch:
                problems.append("%s: header %s, expected %s" % (rel, head, ch))
            if any("time" in h.lower() for h in head):
                problems.append("%s: a column name holds 'time'; Tensorlab drops it" % rel)
            if len(body) < frame:
                problems.append("%s: %d rows, shorter than one frame of %d" % (rel, len(body), frame))
            rows_per_class[lab] = rows_per_class.get(lab, 0) + len(body)
            files.append(rel)
    windows = sum(max(0, (n - frame) // max(1, stride) + 1) for n in rows_per_class.values())
    batch = int(a.batch) if a.batch != "auto" else max(8, min(256, 1 << max(3, (windows // 10).bit_length() - 1)))
    npu_model = a.model.endswith("_NPU")
    if npu_model and a.device not in NPU:
        problems.append("%s has no NPU in TI's device table; TI's own CC2755 example still uses an _NPU model, so check the "
                        "compile log (TI Model Library Memory Usage) before trusting it" % a.device)

    # the dataset zip: classes/ and annotations/ at the top, as Model Composer's import wants
    zpath = os.path.join(tl, "%s_field.zip" % app["name"].replace("-", "_"))
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for root, _, names in os.walk(tl):
            for n in sorted(names):
                p = os.path.join(root, n)
                rel = os.path.relpath(p, tl)
                if rel.split(os.sep)[0] in ("classes", "annotations"):
                    z.write(p, rel)

    y = [
        "# Generated by portability/fielddata/tensorlab.py from %s/schema.json. Edit the knobs, not the dataset block." % os.path.basename(os.path.dirname(od)),
        "# Run:  ./run_tinyml_modelzoo.sh %s" % "config.yaml",
        "# Or:   Edge AI Studio > Model Composer > new project > Import Annotated Archive Dataset > %s" % os.path.basename(zpath),
        "#       then set the same device, model and training values as below.",
        "# Not yet run in Tensorlab here. Keys from TI's docs read 2026-10-17.",
        "common:",
        "  task_type: generic_timeseries_classification",
        "  target_device: %s" % a.device,
        "dataset:",
        "  dataset_name: %s_field" % app["name"].replace("-", "_"),
        "  input_data_path: ./%s   # the folder holding classes/ and annotations/ (the zip unpacked), or the zip" % os.path.basename(zpath),
        ("  # annotations/ sets train, val and test by whole segment or device, so no split keys are given"
         if os.path.isdir(os.path.join(tl, "annotations")) else
         "  # no annotations/: Tensorlab splits the files itself (check the split key names against your installed version)"),
        "data_processing_feature_extraction:",
        "  feature_extraction_name: Custom_Default",
        "  data_proc_transforms: ['SimpleWindow']",
        ("  frame_size: %d          # samples per frame: the schema's window at %s Hz" % (frame, tr.get("rate_hz")) if ts else
         "  frame_size: %d          # best effort: %d consecutive records per frame; they are separate events" % (frame, frame)),
        "  stride_size: %s       # fraction of a frame, as in TI's grid_stability example" % round(stride / frame, 3),
        "  variables: [%s]" % ", ".join("'%s'" % c for c in ch),
    ]
    if ts and tr.get("rate_hz"):
        y.append("  sampling_rate: %s" % tr["rate_hz"])
    y += [
        "training:",
        "  model_name: %s   # one size step at a time: %s" % (a.model, " ".join(SIZES[:8]) + " ..."),
        "  training_epochs: %d" % a.epochs,
        "  batch_size: %d       # about a tenth of %d windows; TI's default is 256" % (batch, windows),
        "  learning_rate: %s" % a.lr,
        "  quantization: %d     # 0 float, 1 PyTorch, 2 TI NPU style" % a.quant,
        "  quantization_method: %s" % ("QAT" if a.qat else "PTQ"),
        "testing: {}",
        "compilation:",
        "  enable: true",
        "# Deploy: from data/projects/%s_field/run/<date-time>/%s/ copy compilation/artifacts/mod.a and tvmgen_default.h,"
        % (app["name"].replace("-", "_"), a.model),
        "# training/quantization/golden_vectors/test_vector.c and user_input_config.h, all from the same run, into the",
        "# SDK's AI example in CCStudio; build, flash, and check the golden vectors pass before trusting a live answer.",
        ""]
    open(os.path.join(tl, "config.yaml"), "w").write("\n".join(y))
    print("%s: %d class files, %s, %d windows of %d -> %s, %s" % (
        app["name"], len(files), ", ".join("%s %d rows" % kv for kv in sorted(rows_per_class.items())), windows, frame,
        os.path.relpath(os.path.join(tl, "config.yaml")), os.path.relpath(zpath)))
    for p in problems:
        print("  check: " + p)


if __name__ == "__main__":
    main()
