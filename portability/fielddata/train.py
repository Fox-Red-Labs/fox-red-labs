#!/usr/bin/env python3
"""Train a small decision tree on any app's gold table and write it as C. Standard library only.
    python3 portability/fielddata/train.py <export dir>/<app>/gold.csv [--depth 5] [--out dir]
Uses every numeric column except the bookkeeping ones as features, the `label` column as the answer, and the `split`
column for train and test. Reports the model against `device_said`, the device's own answer, on the same test rows:
that is the number that says whether the field data was worth collecting. Writes model.json, fd_model.c/.h and MODEL.md."""
import argparse
import csv
import json
import os

SKIP = {"window", "record", "device", "start_utc", "event_time_utc", "label", "device_said", "split"}


def gini(c):
    n = sum(c)
    return 1 - sum((x / n) ** 2 for x in c) if n else 0


def build(X, y, feats, nclass, depth, max_depth, min_leaf, nodes):
    counts = [y.count(k) for k in range(nclass)]
    major = max(range(nclass), key=lambda k: counts[k])
    if depth >= max_depth or len(y) < 2 * min_leaf or max(counts) == len(y):
        nodes.append(dict(leaf=major, n=len(y)))
        return len(nodes) - 1
    best = None
    for f in feats:
        order = sorted(range(len(y)), key=lambda i: X[i][f])
        left, right = [0] * nclass, counts[:]
        for k in range(len(order) - 1):
            i = order[k]
            left[y[i]] += 1
            right[y[i]] -= 1
            a, b = X[i][f], X[order[k + 1]][f]
            if a == b or k + 1 < min_leaf or len(y) - k - 1 < min_leaf:
                continue
            g = ((k + 1) * gini(left) + (len(y) - k - 1) * gini(right)) / len(y)
            if best is None or g < best[0]:
                best = (g, f, (a + b) // 2)
    if best is None or gini(counts) - best[0] < 1e-4:
        nodes.append(dict(leaf=major, n=len(y)))
        return len(nodes) - 1
    _, f, thr = best
    me = len(nodes)
    nodes.append(dict(f=f, thr=thr))
    li = [i for i in range(len(y)) if X[i][f] <= thr]
    ri = [i for i in range(len(y)) if X[i][f] > thr]
    nodes[me]["l"] = build([X[i] for i in li], [y[i] for i in li], feats, nclass, depth + 1, max_depth, min_leaf, nodes)
    nodes[me]["r"] = build([X[i] for i in ri], [y[i] for i in ri], feats, nclass, depth + 1, max_depth, min_leaf, nodes)
    return me


def predict(nodes, x):
    n = nodes[0]
    while "leaf" not in n:
        n = nodes[n["l"]] if x[n["f"]] <= n["thr"] else nodes[n["r"]]
    return n["leaf"]


def confusion(classes, pairs):
    cm = [[0] * len(classes) for _ in classes]
    for t, p in pairs:
        if p in range(len(classes)):
            cm[t][p] += 1
    acc = sum(cm[i][i] for i in range(len(classes))) / max(1, sum(map(sum, cm)))
    return acc, cm


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("gold")
    ap.add_argument("--depth", type=int, default=5)
    ap.add_argument("--min-leaf", type=int, default=5)
    ap.add_argument("--out")
    a = ap.parse_args()
    rows = [r for r in csv.DictReader(open(a.gold)) if r.get("label")]
    if not rows:
        raise SystemExit("no labelled rows in " + a.gold)
    feats = [k for k in rows[0] if k not in SKIP and all(r[k].lstrip("-").isdigit() for r in rows if r[k] != "")]
    classes = sorted({r["label"] for r in rows})
    X = [{f: int(r[f] or 0) for f in feats} for r in rows]
    y = [classes.index(r["label"]) for r in rows]
    tr = [i for i, r in enumerate(rows) if r.get("split") != "test"]
    te = [i for i, r in enumerate(rows) if r.get("split") == "test"] or tr
    nodes = []
    build([X[i] for i in tr], [y[i] for i in tr], feats, len(classes), 0, a.depth, a.min_leaf, nodes)
    acc, cm = confusion(classes, [(y[i], predict(nodes, X[i])) for i in te])
    base_acc, base_cm = confusion(classes, [(y[i], classes.index(rows[i]["device_said"]) if rows[i]["device_said"] in classes else -1)
                                            for i in te])
    out = a.out or os.path.join(os.path.dirname(os.path.abspath(a.gold)), "model")
    os.makedirs(out, exist_ok=True)
    json.dump(dict(features=feats, classes=classes, nodes=nodes, test_rows=len(te), train_rows=len(tr), accuracy=acc,
                   device_accuracy=base_acc, confusion=cm, device_confusion=base_cm), open(os.path.join(out, "model.json"), "w"), indent=1)
    lines = ["/* Generated by portability/fielddata/train.py from %s. Do not edit. */" % os.path.basename(a.gold),
             "#include \"fd_model.h\"", "",
             "/* inputs, in this order: %s */" % ", ".join(feats),
             "typedef struct { int8_t f; int32_t thr; uint16_t l, r; } fd_node_t;",
             "static const fd_node_t TREE[%d] = {" % len(nodes)]
    for n in nodes:
        lines.append("    { -1, %d, 0, 0 },   /* %s */" % (n["leaf"], classes[n["leaf"]]) if "leaf" in n else
                     "    { %d, %d, %d, %d },   /* %s <= %d */" % (feats.index(n["f"]), n["thr"], n["l"], n["r"], n["f"], n["thr"]))
    lines += ["};", "", "uint8_t fd_model_classify(const int32_t *x)", "{", "    const fd_node_t *n = TREE;",
              "    while (n->f >= 0) n = (x[n->f] <= n->thr) ? &TREE[n->l] : &TREE[n->r];", "    return (uint8_t)n->thr;", "}", ""]
    open(os.path.join(out, "fd_model.c"), "w").write("\n".join(lines))
    open(os.path.join(out, "fd_model.h"), "w").write(
        "/* Generated by portability/fielddata/train.py. */\n#ifndef FD_MODEL_H\n#define FD_MODEL_H\n#include <stdint.h>\n"
        "#define FD_MODEL_INPUTS %d\n/* classes: %s */\nuint8_t fd_model_classify(const int32_t *x);\n#endif\n" % (len(feats), ", ".join(classes)))
    card = ["# Model card", "", "Trained by `portability/fielddata/train.py` on `%s`: %d training rows, %d test rows, %d features, %d nodes." % (
        os.path.basename(a.gold), len(tr), len(te), len(feats), len(nodes)), "",
        "| | Test accuracy |", "|---|---|", "| This model | %.1f%% |" % (100 * acc), "| The device's own answer | %.1f%% |" % (100 * base_acc), "",
        "Confusion, model (rows true, columns predicted: %s):" % ", ".join(classes), ""] + \
        ["    %-8s %s" % (c, " ".join("%5d" % v for v in row)) for c, row in zip(classes, cm)] + ["", "Inputs: " + ", ".join(feats), ""]
    open(os.path.join(out, "MODEL.md"), "w").write("\n".join(card))
    print("model %.1f%% vs the device's own answer %.1f%% on %d test rows (%d nodes) -> %s" % (
        100 * acc, 100 * base_acc, len(te), len(nodes), out))


if __name__ == "__main__":
    main()
