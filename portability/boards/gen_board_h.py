#!/usr/bin/env python3
"""Write bench_board.h for one board from portability/boards/boards.csv, or check the table.

    gen_board_h.py <board> <out.h>     header for one board (exit 2 if the board or a needed cell is missing)
    gen_board_h.py --check             every cpu_mhz agrees with data/boards.csv clock_mhz; timer_mhz divides cpu_mhz
"""
import csv, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
TABLE = {r["board"]: r for r in csv.DictReader((HERE / "boards.csv").open())}


def header(b):
    r = TABLE.get(b)
    if r is None:
        sys.exit(f"gen_board_h: board '{b}' is not in {HERE / 'boards.csv'}")
    cpu = int(float(r["cpu_mhz"]) * 1e6)
    out = [f"/* bench_board.h for {b}, generated by portability/boards/gen_board_h.py from boards.csv. Do not edit. */",
           "#ifndef BENCH_BOARD_H_", "#define BENCH_BOARD_H_",
           f'#define BB_ID "{b}"', f"#define BB_CPU_HZ {cpu}u"]
    if r["timer_mhz"]:
        t = int(float(r["timer_mhz"]) * 1e6)
        if cpu % t:
            sys.exit(f"gen_board_h: {b}: cpu_mhz must be a multiple of timer_mhz")
        out += [f"#define BB_TIMER_HZ {t}u", f"#define BB_TIMER_DIV {cpu // t}u   /* CPU cycles per timer count */"]
    for key, name in (("cycle_counter", "COUNTER"), ("led", "LED"), ("uart", "UART"), ("adc", "ADC")):
        if r[key]:
            out.append(f'#define BB_{name} "{r[key]}"')
    out.append("#endif")
    return "\n".join(out) + "\n"


def check():
    bad = 0
    boards = {r["board"]: r for r in csv.DictReader((REPO / "data/boards.csv").open())}
    for b, r in TABLE.items():
        if b not in boards:
            print(f"{b}: not in data/boards.csv"); bad += 1
        elif float(boards[b]["clock_mhz"]) != float(r["cpu_mhz"]):
            print(f"{b}: cpu_mhz {r['cpu_mhz']} but data/boards.csv says {boards[b]['clock_mhz']}"); bad += 1
        if r["timer_mhz"] and float(r["cpu_mhz"]) % float(r["timer_mhz"]):
            print(f"{b}: timer_mhz does not divide cpu_mhz"); bad += 1
    print(("FAIL" if bad else "OK") + f": {len(TABLE)} boards, {bad} problems")
    return 1 if bad else 0


if __name__ == "__main__":
    if sys.argv[1:] == ["--check"]:
        sys.exit(check())
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    Path(sys.argv[2]).write_text(header(sys.argv[1]))
