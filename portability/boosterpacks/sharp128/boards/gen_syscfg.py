#!/usr/bin/env python3
"""Write boards/<board>/sharp128.syscfg for the MSPM0 hosts from one pin table.

Pins are BoosterPack header pin -> MCU pin, read from TI's LaunchPad board files in the MSPM0 SDK 2.11
(source/ti/boards/.meta/LP_*.syscfg.json) and checked against SLAU786 Tables 1 to 3.
    2 LCD power   5 DISP   6 LCD select (high = selected)   7 SPI clock   15 SPI data out   14 SPI data in
    8 SD select (low = selected)   17 card detect (low = card in)
Run:  python3 gen_syscfg.py        (rewrites the syscfg files; the build runs SysConfig on them)
"""
import os

BOARDS = {
    # id: (cli device, cli package, v2 device, spi instance, sclk, mosi, miso, pwr, disp, lcd_cs, sd_cs, sd_det)
    "mspm0g3519": ("MSPM0G351X", "LQFP-100(PZ)", "MSPM0G3519", "SPI1", "PB31", "PB8", "PB7", "PA14", "PB29", "PA25", "PB30", "PA30"),
    "mspm0g3507": ("MSPM0G350X", "LQFP-64(PM)", "MSPM0G3507", "SPI1", "PB9", "PB8", "PB7", "PA25", "PA26", "PB24", "PA27", "PB15"),
    # L1306: no SD (4 kB RAM). C1104: SD select on PA22 (pull J7: LED1), no detect wire (pin 17 is the debug data line SWDIO)
    "mspm0l1306": ("MSPM0L130X", "VQFN-32(RHB)", "MSPM0L1306", "SPI0", "PA6", "PA5", "PA4", "PA25", "PA24", "PA21", None, None),
    "mspm0c1104": ("MSPM0C110X", "VSSOP-20(DGS20)", "MSPM0C1104", "SPI0", "PA6", "PA18", "PA4", "PA25", "PA24", "PA28", "PA22", None),
}

def group(var, name, pin, direction="OUTPUT", initial=None, pull=None):
    # group GP_<X>, pin PIN_<X>: SysConfig makes GP_<X>_PORT and GP_<X>_PIN_<X>_PIN (pin names must be unique)
    port = "PORT" + pin[1]
    s = [f'const {var} = GPIO.addInstance();',
         f'{var}.$name = "GP_{name}";',
         f'{var}.port  = "{port}";',
         f'{var}.associatedPins[0].$name = "PIN_{name}";',
         f'{var}.associatedPins[0].assignedPin = "{pin[2:]}";']
    if direction == "INPUT":
        s.append(f'{var}.associatedPins[0].direction = "INPUT";')
    if pull:
        s.append(f'{var}.associatedPins[0].internalResistor = "{pull}";')
    if initial:
        s.append(f'{var}.associatedPins[0].initialValue = "{initial}";')
    return "\n".join(s)

for b, (dev, pkg, v2, spi, sclk, mosi, miso, pwr, disp, lcs, scs, sdet) in BOARDS.items():
    parts = [f'''//@cliArgs --device "{dev}" --package "{pkg}" --part "Default"
//@v2CliArgs --device "{v2}" --package "{pkg}"
// @cliArgs --board /ti/boards/LP_{v2} --rtos nortos
// BOOSTXL-SHARP128 on the LP-{v2}. Generated by boards/gen_syscfg.py; edit the table there.
// SPI mode 0, MSB first, 8-bit frames, 1 MHz (the panel's rate); chip selects are plain GPIO.
const GPIO   = scripting.addModule("/ti/driverlib/GPIO", {{}}, false);
const SPI    = scripting.addModule("/ti/driverlib/SPI", {{}}, false);
const Board  = scripting.addModule("/ti/driverlib/Board", {{}}, false);
const SYSCTL = scripting.addModule("/ti/driverlib/SYSCTL", {{}}, false);
const SHARP_SPI_V = SPI.addInstance();
''']
    parts.append(group("g_pwr", "PWR", pwr))
    parts.append(group("g_disp", "DISP", disp))
    parts.append(group("g_lcs", "LCD_CS", lcs))
    if scs:
        parts.append(group("g_scs", "SD_CS", scs, initial="SET"))
    if sdet:
        parts.append(group("g_det", "SD_DET", sdet, direction="INPUT", pull="PULL_UP"))
    clk = ('SYSCTL.forceDefaultClkConfig = true;\nSYSCTL.clockTreeEn           = true;' if b.startswith('mspm0g') else '// default clock tree')
    parts.append(f'''
SHARP_SPI_V.$name                      = "SHARP_SPI";
SHARP_SPI_V.targetBitRate              = 1000000;
SHARP_SPI_V.frameFormat                = "MOTO3";
SHARP_SPI_V.peripheral.$assign         = "{spi}";
SHARP_SPI_V.peripheral.sclkPin.$assign = "{sclk}";
SHARP_SPI_V.peripheral.mosiPin.$assign = "{mosi}";
SHARP_SPI_V.peripheral.misoPin.$assign = "{miso}";

{clk}
''')
    d = os.path.join(os.path.dirname(os.path.abspath(__file__)), b)
    os.makedirs(d, exist_ok=True)
    open(os.path.join(d, "sharp128.syscfg"), "w").write("\n".join(parts))
    print("wrote", b)
