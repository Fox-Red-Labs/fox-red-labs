#!/usr/bin/env python3
"""Generate one board's SysConfig file, board_config.h and PINS.md from boards/<board>/pins.json.

  gen_board.py <board> <out_dir> [--lcd | --no-lcd]

The pin map lives in pins.json only; the SysConfig file, the C header the port reads and the
pin table in the docs all come from it, so they cannot disagree. Run from anywhere.
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUTPUTS = ["LCD_CS", "LCD_DC", "LCD_RST", "BL_RED", "LED_GREEN", "LED_BLUE", "BUZZER"]
INPUTS = ["S1", "S2", "JOY_SEL"]
ADC_ORDER = ["JOY_X", "JOY_Y", "MIC", "ACC_X", "ACC_Y", "ACC_Z"]   # edumkii_adc_t order
INIT_HIGH = {"LCD_CS", "LCD_DC", "LCD_RST"}


def load(board, lcd):
    c = json.load(open(os.path.join(ROOT, "boards", board, "pins.json")))
    c["lcd_on"] = bool(c.get("lcd")) if lcd is None else lcd
    if c["lcd_on"] and not c.get("lcd"):
        v = c["lcd_variant"]
        c["gpio"].update(v["gpio"]); c["spi"] = v["spi"]
    if not c["lcd_on"]:
        for k in ("LCD_CS", "LCD_DC", "LCD_RST"):
            c["gpio"].pop(k, None)
        c.pop("spi", None)
    # Optional console changes for apps that talk to a host: EDU_UART_RX=1 also receives (RX is the backchannel pin, which the
    # board's S1 uses, so S1 is dropped); EDU_UART_BAUD=<n> sets the rate.
    if os.environ.get("EDU_UART_RX") == "1":
        c["uart"]["rx"] = c["bp"]["33"]
        for k, v in list(c["gpio"].items()):
            if v == c["uart"]["rx"]: del c["gpio"][k]
    if os.environ.get("EDU_UART_BAUD"): c["uart"]["baud"] = int(os.environ["EDU_UART_BAUD"])
    return c


def syscfg(c):
    L = []
    head = c["sysconfig_head"]
    L.append("//@cliArgs " + head[0])
    L.append("//@v2CliArgs " + head[1])
    L.append("// Generated by tools/gen_board.py from boards/%s/pins.json. Do not edit." % c["board"])
    mspm0 = c["family"] == "mspm0"
    L.append('const GPIO = scripting.addModule("/ti/driverlib/GPIO", {}, false);')
    names = sorted(c["gpio"])
    for i, n in enumerate(names):
        L.append("const GPIO%d = GPIO.addInstance();" % i)
    if "spi" in c: L.append('const SPI  = scripting.addModule("/ti/driverlib/SPI", {}, false);\nconst SPI1 = SPI.addInstance();')
    if c.get("spi", {}).get("dma"): L.append('const DMA  = scripting.addModule("/ti/driverlib/DMA", {}, false);\nconst DMA1 = DMA.addInstance();')
    L.append('const UART  = scripting.addModule("/ti/driverlib/UART", {}, false);\nconst UART1 = UART.addInstance();')
    ak = c["adc"]["kind"]
    if ak == "adc12":
        insts = sorted({v[0] for v in c["adc"]["map"].values()})
        L.append('const ADC12 = scripting.addModule("/ti/driverlib/ADC12", {}, false);')
        for k, _ in enumerate(insts): L.append("const ADC12_%d = ADC12.addInstance();" % k)
    else:
        L.append('const HSADC = scripting.addModule("/ti/driverlib/HSADC", {}, false);\nconst HSADC1 = HSADC.addInstance();')
    L.append("")
    for i, n in enumerate(names):
        L.append('GPIO%d.$name = "E_%s";' % (i, n))
        L.append('GPIO%d.associatedPins[0].$name = "%s";' % (i, n))
        if n in INPUTS or n in ("I2C_SCL", "I2C_SDA"):
            L.append('GPIO%d.associatedPins[0].direction = "INPUT";' % i)
        else:
            L.append('GPIO%d.associatedPins[0].initialValue = "%s";' % (i, "SET" if n in INIT_HIGH else "CLEARED"))
        L.append('GPIO%d.associatedPins[0].pin.$assign = "%s";' % (i, c["gpio"][n]))
    if "spi" in c:
        s = c["spi"]
        L.append('SPI1.$name = "SPI_LCD";')
        L.append('SPI1.targetBitRate = %d;' % s["bitrate"])
        L.append('SPI1.frameFormat = "MOTO4";')
        if s.get("peripheral"): L.append('SPI1.peripheral.$assign = "%s";' % s["peripheral"])
        L.append('SPI1.peripheral.sclkPin.$assign = "%s";' % s["sclk"])
        L.append('SPI1.peripheral.mosiPin.$assign = "%s";' % s["mosi"])
        L.append('SPI1.peripheral.misoPin.$assign = "%s";' % s["miso"])
        if s.get("dma"):
            L.append('SPI1.rxFifoThreshold = "DL_SPI_RX_FIFO_LEVEL_ONE_FRAME";')
            L.append('SPI1.txFifoThreshold = "DL_SPI_TX_FIFO_LEVEL_EMPTY";')
            L.append('SPI1.enabledDMAEvent2Triggers = "DL_SPI_DMA_INTERRUPT_TX";')
            L.append('SPI1.enabledInterrupts = ["DMA_DONE_TX"];')
            L.append('DMA1.$name = "DMA0";')
            L.append('SPI1.DMA_CHANNEL_EVENT2.$name = "CH1";')
            L.append('SPI1.DMA_CHANNEL_EVENT2.srcLength = "BYTE";')
            L.append('SPI1.DMA_CHANNEL_EVENT2.dstLength = "BYTE";')
            L.append('SPI1.DMA_CHANNEL_EVENT2.addressMode = "b2b";')
            L.append('SPI1.DMA_CHANNEL_EVENT2.dstIncDec = "UNCHANGED";')
            L.append('SPI1.DMA_CHANNEL_EVENT2.peripheral.$assign = "DMA0_CH1";')
    u = c["uart"]
    L.append('UART1.$name = "UART_CONSOLE";')
    L.append('UART1.direction = "%s";' % ("TX_RX" if u.get("rx") else "TX"))
    L.append('UART1.targetBaudRate = %d;' % u["baud"])
    if u.get("peripheral"): L.append('UART1.peripheral.$assign = "%s";' % u["peripheral"])
    L.append('UART1.peripheral.txPin.$assign = "%s";' % u["tx"])
    if u.get("rx"):
        L.append('UART1.peripheral.rxPin.$assign = "%s";' % u["rx"])
        L.append('UART1.enabledInterrupts = ["RX"];')
        L.append('UART1.rxFifoThreshold = "DL_UART_RX_FIFO_LEVEL_ONE_ENTRY";')
    if ak == "adc12":
        for k, inst in enumerate(insts):
            mine = sorted((v[1], v[2]) for v in c["adc"]["map"].values() if v[0] == inst)
            L.append('ADC12_%d.$name = "ADC12_%d";' % (k, k))
            L.append('ADC12_%d.sampClkSrc = "DL_ADC12_CLOCK_ULPCLK";' % k)
            L.append('ADC12_%d.sampClkDiv = "DL_ADC12_CLOCK_DIVIDE_8";' % k)
            L.append('ADC12_%d.sampleTime0 = "25 us";' % k)
            L.append('ADC12_%d.powerDownMode = "DL_ADC12_POWER_DOWN_MODE_MANUAL";' % k)
            L.append('ADC12_%d.adcMem0chansel = "DL_ADC12_INPUT_CHAN_%d";' % (k, mine[0][0]))
            L.append('ADC12_%d.peripheral.$assign = "%s";' % (k, inst))
            L.append('ADC12_%d.peripheral.adcPin%d.$assign = "%s";' % (k, mine[0][0], mine[0][1]))
    else:
        soc = sorted((v[0], v[1], k) for k, v in c["adc"]["map"].items())
        L.append('HSADC1.$name = "HSADC1";')
        L.append('HSADC1.adcBase = "HSADC1_BASE";')
        L.append('HSADC1.enabledSOCs = [%s];' % ",".join('"ADC_SOC_NUMBER%d"' % i for i in range(len(soc))))
        for i, (ch, pin, _) in enumerate(soc): L.append('HSADC1.soc%dChannel = "ADC_CH_ADCIN_%d";' % (i, ch))
        L.append('HSADC1.enabledSEQs = ["ADC_SEQ_NUMBER1"];')
        L.append('HSADC1.seqEndSOC = "ADC_SOC_NUMBER%d";' % (len(soc) - 1))
        L.append('HSADC1.seq1Enable = true;')
        L.append('HSADC1.seq1SampleWindow = 64;')
        L.append('HSADC1.peripheral.$assign = "ADC1";')
        for ch, pin, k in soc: L.append('HSADC1.peripheral.adcPin%d.$assign = "%s";' % (ch, pin))
    L.append("")
    if mspm0:
        L.append('const Board = scripting.addModule("/ti/driverlib/Board", {}, false);')
        L.append('const SYSCTL = scripting.addModule("/ti/driverlib/SYSCTL");')
        for s in c.get("sysctl", []): L.append("SYSCTL.%s;" % s)
    else:
        L.append('const Board = scripting.addModule("/ti/driverlib/Board", {}, false);')
        L.append('Board.peripheral.$assign = "DEBUGSS";\nBoard.peripheral.swclkPin.$assign = "PA20";\nBoard.peripheral.swdioPin.$assign = "PA19";')
        L.append('const SYSCTL = scripting.addModule("/ti/driverlib/SYSCTL");')
        L.append('SYSCTL.peripheral.$assign = "SYSCTL";')
        L.append("SYSCTL.forceDefaultClkConfig = true;")
        if os.environ.get("EDU_CLK160") == "1":
            # CPU at 160 MHz: the system oscillator times the PLL (32 MHz x 10 / 2) with no divider after it, as TI's
            # driverlib/sysctl_mclk_syspll example does, without its CLKOUT pin.
            # The flash then needs 2 wait states and the code cache; the generated init sets both.
            for ln in ('const multiplier2 = system.clockTree["PLL_QDIV"];', 'multiplier2.multiplyValue = 10;',
                       'const divider3 = system.clockTree["EXTDIVMCLK"];', 'divider3.divideValue = 1;'):   # no divide-by-2 after the PLL
                L.append(ln)
            for k, v in (("SYSPLL_Pdiv", "1"), ("MCLKSource", '"HSCLK"'), ("SYSPLL_CLK0En", "true"), ("SYSPLL_CLK1En", "true"), ("SYSPLL_CLK2XEn", "true"), ("clockTreeEn", "true")):
                L.append("SYSCTL.%s = %s;" % (k, v))
    L.append('const ProjectConfig = scripting.addModule("/ti/project_config/ProjectConfig", {}, false);')
    L.append("ProjectConfig.migrationCondition = true;")
    return "\n".join(L) + "\n"


def header(c):
    H = ["/* Generated by tools/gen_board.py from boards/%s/pins.json. Do not edit. */" % c["board"],
         "#ifndef BOARD_CONFIG_H", "#define BOARD_CONFIG_H",
         '#define EDU_BOARD_NAME "%s"' % c["board"],
         "#define EDU_FAMILY_%s 1" % c["family"].upper()]
    if c["lcd_on"]: H.append("#define EDU_HAS_LCD 1")
    if "spi" in c and c["spi"].get("dma"): H.append("#define EDU_SPI_DMA 1")
    for n in c["gpio"]: H.append("#define EDU_HAS_%s 1" % n)
    H.append("#define EDU_HAS_UART 1")
    if c["uart"].get("rx"): H.append("#define EDU_HAS_UART_RX 1")
    if c.get("joy_sel_raw"):
        j = c["joy_sel_raw"]
        H.append("#define EDU_JOYSEL_RAW { %s, %s, %s }" % (j["port"], j["pin"], j["iomux"]))
        H.append("#define EDU_HAS_JOY_SEL_RAW 1")
    if c.get("joy_sel_adc"):
        j = c["joy_sel_adc"]
        H.append("#define EDU_JOYSEL_ADC { ADC12_0_INST, DL_ADC12_INPUT_CHAN_%d }" % j[1])
        H.append("#define EDU_HAS_JOY_SEL_ADC 1")
    ak = c["adc"]["kind"]
    if ak == "adc12":
        insts = sorted({v[0] for v in c["adc"]["map"].values()})
        H.append("#define EDU_ADC12 1")
        H.append("/* per signal: ADC12 instance and input channel; instance 0 means not wired on this LaunchPad */")
        H.append("#define EDU_ADC_TABLE \\")
        rows = []
        for n in ADC_ORDER:
            v = c["adc"]["map"].get(n)
            rows.append("    { %s, %s }" % (("ADC12_%d_INST" % insts.index(v[0]), "DL_ADC12_INPUT_CHAN_%d" % v[1]) if v else ("0", "0")))
        H.append(", \\\n".join(rows))
    else:
        H.append("#define EDU_HSADC 1")
        order = sorted((v[0], k) for k, v in c["adc"]["map"].items())
        H.append("#define EDU_HSADC_SOC_TABLE { %s }" % ", ".join(
            str(order.index((c["adc"]["map"][n][0], n))) for n in ADC_ORDER))
        if "SEL_DIAG" in c["adc"]["map"]:
            H.append("#define EDU_HSADC_SEL_SOC %d" % order.index((c["adc"]["map"]["SEL_DIAG"][0], "SEL_DIAG")))
    H.append("#endif")
    return "\n".join(H) + "\n"


def pins_md(c):
    names = {}
    for n, p in c["gpio"].items(): names[p] = n
    fn = {2: "joystick X (analog)", 5: "joystick press", 6: "microphone (analog)", 7: "screen clock", 9: "I2C clock (light sensor)",
          10: "I2C data (light sensor)", 13: "screen select", 15: "screen data in", 17: "screen reset", 23: "accelerometer X (analog)",
          24: "accelerometer Y (analog)", 25: "accelerometer Z (analog)", 26: "joystick Y (analog)", 31: "screen data/command",
          32: "button S2", 33: "button S1", 34: "gator clip (console TX in the hello example)", 37: "blue LED", 38: "green LED",
          39: "red LED or backlight (J5)", 40: "buzzer"}
    M = ["# %s pin map for the Educational BoosterPack MKII" % c["launchpad"], "",
         "BoosterPack pin number, the LaunchPad pin it reaches, and what to do about it.", "",
         "Terms: [docs/vocab.md](../../../../../docs/vocab.md).", "",
         "| BoosterPack pin | Function | LaunchPad pin | Note |", "|---|---|---|---|"]
    for k in sorted(c.get("notes", {}), key=int):
        if c["notes"][k].startswith("WARNING"):
            M[4:4] = ["**Warning, BoosterPack pin %s.** %s." % (k, c["notes"][k][len("WARNING: "):]), ""]
    for k in sorted(fn):
        p = c["bp"].get(str(k), "not listed")
        M.append("| %d | %s | %s | %s |" % (k, fn[k], p, c.get("notes", {}).get(str(k), "")))
    return "\n".join(M) + "\n"


def main():
    if len(sys.argv) < 3: sys.exit(__doc__)
    lcd = None
    if "--lcd" in sys.argv: lcd = True
    if "--no-lcd" in sys.argv: lcd = False
    c = load(sys.argv[1], lcd)
    out = sys.argv[2]
    os.makedirs(out, exist_ok=True)
    open(os.path.join(out, "edumkii.syscfg"), "w").write(syscfg(c))
    open(os.path.join(out, "board_config.h"), "w").write(header(c))
    if "--pins-md" in sys.argv:
        c2 = load(sys.argv[1], None)
        open(os.path.join(ROOT, "boards", sys.argv[1], "PINS.md"), "w").write(pins_md(c2))


main()
