#!/usr/bin/env python3
"""Write the C table of recorded tracks for the Halloween show from one or more track folders (made by add_track.py).
  python3 tools/tracks2c.py <out.c> <folder> [<folder> ...]
A folder that does not exist is skipped. Tracks are ordered by name within each folder."""
import json, pathlib, sys

out, dirs = sys.argv[1], sys.argv[2:]
items = []
for d in dirs:
    p = pathlib.Path(d).expanduser()
    if not p.is_dir(): continue
    for j in sorted(p.glob("*.json")):
        m = json.loads(j.read_text()); b = (p / f"{m['name']}.ima").read_bytes()
        items.append((m, b))
lines = ["/* Generated by tools/tracks2c.py. Do not edit. */", '#include "ba_adpcm.h"']
for m, b in items:
    lines.append(f"static const uint8_t t_{m['name']}[{len(b)}] = {{")
    for i in range(0, len(b), 32): lines.append("  " + ",".join(str(v) for v in b[i:i + 32]) + ",")
    lines.append("};")
def q(s): return '"' + s.replace("\\", "\\\\").replace('"', "'") + '"'
lines.append(f"const ba_track_t ba_tracks[{max(1, len(items))}] = {{")
for m, b in items:
    lines.append(f"  {{ {q(m['title'])}, {q((m.get('credit') or '') + ' (' + m.get('license', '') + ')')}, t_{m['name']}, {m['nsamples']}u, {m['rate']}u }},")
if not items: lines.append("  { 0, 0, 0, 0u, 0u },")
lines += ["};", f"const uint8_t ba_tracks_n = {len(items)};", ""]
pathlib.Path(out).write_text("\n".join(lines))
print(f"{len(items)} tracks, {sum(len(b) for _, b in items)} bytes")
