#!/usr/bin/env python3
"""Write core/ba_sine_table.h: 256 int16 sine samples. Run from this folder: python3 tools/gen_sine.py"""
import math, pathlib
t = [round(32767 * math.sin(2 * math.pi * i / 256)) for i in range(256)]
out = ["/* 256-entry sine table, int16, generated by tools/gen_sine.py (math.sin, rounded). */",
       "#ifndef BA_SINE_TABLE_H", "#define BA_SINE_TABLE_H", "#include <stdint.h>", "static const int16_t ba_sine_tab[256] = {"]
for i in range(0, 256, 8):
    out.append("  " + ", ".join(str(x) for x in t[i:i + 8]) + ",")
out += ["};", "#endif", ""]
pathlib.Path(__file__).resolve().parent.parent.joinpath("core", "ba_sine_table.h").write_text("\n".join(out))
