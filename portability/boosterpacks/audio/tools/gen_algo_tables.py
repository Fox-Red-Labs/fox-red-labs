#!/usr/bin/env python3
"""Write algos/ba_algo_tables.h: FFT twiddles (128-point), Hann window (128) and DTMF Goertzel coefficients, all Q-format integers.
   python3 tools/gen_algo_tables.py > algos/ba_algo_tables.h"""
import math
N = 128
def q15(v): return max(-32768, min(32767, int(round(v * 32768))))
out = ["/* Generated by tools/gen_algo_tables.py. Do not edit by hand. */", "#ifndef BA_ALGO_TABLES_H", "#define BA_ALGO_TABLES_H", "#include <stdint.h>", ""]
out.append("/* cos and -sin of 2*pi*k/128 for k = 0..63, Q15 */")
out.append("static const int16_t ba_fft_cos[64] = {" + ",".join(str(q15(math.cos(2*math.pi*k/N))) for k in range(64)) + "};")
out.append("static const int16_t ba_fft_nsin[64] = {" + ",".join(str(q15(-math.sin(2*math.pi*k/N))) for k in range(64)) + "};")
out.append("/* Hann window, 128 points, Q15 */")
out.append("static const int16_t ba_hann128[128] = {" + ",".join(str(q15(0.5-0.5*math.cos(2*math.pi*n/N))) for n in range(N)) + "};")
f = [697, 770, 852, 941, 1209, 1336, 1477, 1633]
out.append("/* DTMF Goertzel coefficients 2*cos(2*pi*f/8000), Q14, for the 4 row and 4 column tones at 8 kHz */")
out.append("static const int32_t ba_dtmf_coef[8] = {" + ",".join(str(int(round(2*math.cos(2*math.pi*x/8000)*16384))) for x in f) + "};")
out.append("#endif")
print("\n".join(out))
