#!/usr/bin/env python3
"""Turn a .tune text file into a C header for core/ba_chip.h.  python3 tools/tune2h.py songs/fox_run.tune songs/fox_run.h fox_run

Format: '#' starts a comment. 'tempo N' beats per minute (one row is an eighth note, so a row lasts 30/N seconds).
'vol a b c d' sets the four voice volumes, 0 to 15.
A 'tempo' line after the first row of notes changes the tempo from the next row on (an accelerando is a run of them); the
header then also holds NAME_marks[][2] = {row, tempo} and NAME_NMARKS, which a player applies as it reaches each row. Every other line is one bar of rows: four columns separated by '|',
each column a list of tokens, one token per row. Tonal columns: note name (C4 to B7, # for sharp), '-' hold, '.' rest.
Drum column: k kick, s snare, h hat, '-' hold, '.' rest.  Middle C is C4 = MIDI 60.
"""
import re, sys, pathlib

NOTES = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}
DRUMS = {"k": 2, "s": 3, "h": 4}


def note(tok):
    m = re.fullmatch(r"([A-G])(#?)(\d)", tok)
    if not m:
        raise ValueError(f"bad note {tok!r}")
    n = 12 * (int(m.group(3)) + 1) + NOTES[m.group(1)] + (1 if m.group(2) else 0)
    if not 12 <= n <= 119:
        raise ValueError(f"note out of range {tok!r}")
    return n


def parse(text):
    tempo, vol, rows, marks = 120, [10, 8, 12, 8], [], []
    for ln in text.splitlines():
        ln = ln.split("#", 1)[0] if not re.match(r"^\s*[A-G]#?\d|^\s*[.\-khs]", ln) else ln
        ln = re.sub(r"\s+#.*$", "", ln).strip()
        if not ln:
            continue
        if ln.startswith("tempo"):
            t = int(ln.split()[1])
            if rows:
                if marks and marks[-1][0] == len(rows): marks[-1] = (len(rows), t)
                else: marks.append((len(rows), t))
            else:
                tempo = t
            continue
        if ln.startswith("vol"):
            vol = [int(x) for x in ln.split()[1:5]]; continue
        cols = [c.split() for c in ln.split("|")]
        if len(cols) != 4 or len({len(c) for c in cols}) != 1:
            raise ValueError(f"need four columns of equal length: {ln!r}")
        for i in range(len(cols[0])):
            r = []
            for v in range(4):
                t = cols[v][i]
                if t == ".": r.append(0)
                elif t == "-": r.append(1)
                elif v == 3: r.append(DRUMS[t])
                else: r.append(note(t))
            rows.append(r)
    return tempo, vol, rows, marks


def seconds(tempo, rows, marks):
    t, mi, sec = tempo, 0, 0.0
    for r in range(len(rows)):
        while mi < len(marks) and marks[mi][0] == r: t = marks[mi][1]; mi += 1
        sec += 30.0 / t
    return sec


def main():
    src, dst, name = sys.argv[1], sys.argv[2], sys.argv[3]
    tempo, vol, rows, marks = parse(pathlib.Path(src).read_text())
    out = [f"/* Generated by tools/tune2h.py from {pathlib.Path(src).name}. Do not edit. */",
           f"#ifndef SONG_{name.upper()}_H", f"#define SONG_{name.upper()}_H", '#include "ba_chip.h"',
           f"#define {name.upper()}_TEMPO {tempo}", f"#define {name.upper()}_VOL {{{', '.join(str(v) for v in vol)}}}", f"static const uint8_t {name}_rows[{len(rows)}][4] = {{"]
    out += ["  {" + ", ".join(str(x) for x in r) + "}," for r in rows]
    out += ["};", f"/* samples_per_row = rate * 30 / tempo */"]
    if marks:
        out += [f"#define {name.upper()}_NMARKS {len(marks)}", f"static const uint16_t {name}_marks[{len(marks)}][2] = {{ /* row, tempo from that row on */"]
        out += ["  {" + f"{r}, {t}" + "}," for r, t in marks]
        out += ["};"]
    out += ["#endif", ""]
    pathlib.Path(dst).write_text("\n".join(out))
    nbytes = len(rows) * 4 + len(marks) * 4
    extra = f", {len(marks)} tempo changes to {marks[-1][1]}" if marks else ""
    print(f"{name}: {len(rows)} rows, tempo {tempo}{extra}, volumes {vol}, {nbytes} bytes of flash, {seconds(tempo, rows, marks):.1f} s")


if __name__ == "__main__":
    main()
