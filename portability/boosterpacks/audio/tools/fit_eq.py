"""python3 tools/fit_eq.py <response.json> halloween/ba_eq_coeffs.h
Fit the speaker EQ from the measured response (Mac microphone, assumed flat; see README) and write the Q14
biquad coefficients for halloween/ba_eq.c. RBJ cookbook biquads at 16 kHz."""
import json, math, sys
fs = 16000.0
meas = json.load(open(sys.argv[1]))
def peq(f0, g, q):
    A = 10 ** (g / 40); w = 2 * math.pi * f0 / fs; al = math.sin(w) / (2 * q); c = math.cos(w)
    b = [1 + al * A, -2 * c, 1 - al * A]; a = [1 + al / A, -2 * c, 1 - al / A]
    return [v / a[0] for v in b], [1, a[1] / a[0], a[2] / a[0]]
def hp(f0, q=0.707):
    w = 2 * math.pi * f0 / fs; al = math.sin(w) / (2 * q); c = math.cos(w)
    b = [(1 + c) / 2, -(1 + c), (1 + c) / 2]; a = [1 + al, -2 * c, 1 - al]
    return [v / a[0] for v in b], [1, a[1] / a[0], a[2] / a[0]]
def lp(f0, q=0.707):
    w = 2 * math.pi * f0 / fs; al = math.sin(w) / (2 * q); c = math.cos(w)
    b = [(1 - c) / 2, 1 - c, (1 - c) / 2]; a = [1 + al, -2 * c, 1 - al]
    return [v / a[0] for v in b], [1, a[1] / a[0], a[2] / a[0]]
def resp(bq, f):
    z = complex(math.cos(2 * math.pi * f / fs), math.sin(2 * math.pi * f / fs)); h = 1
    for b, a in bq: h *= (b[0] + b[1] / z + b[2] / z / z) / (a[0] + a[1] / z + a[2] / z / z)
    return 20 * math.log10(abs(h))
eq = [hp(300), peq(540, 5.0, 1.0), peq(1000, -7.0, 2.5), peq(1650, 8.0, 2.0), peq(2400, -3.0, 2.5), peq(4300, 4.0, 1.5)]
bass = [lp(300), lp(300)]          # the band the speaker cannot play, before the harmonic generator
harm = [hp(350), lp(1200)]         # where its harmonics go
print("f    measured  eq   predicted")
band = []
for f, m in sorted(((int(k), v) for k, v in meas.items())):
    g = resp(eq, f); band.append((f, m + g))
    print(f"{f:5d} {m:7.1f} {g:5.1f} {m + g:7.1f}")
sel = [p for f, p in band if 500 <= f <= 4000]
selm = [meas[str(f)] for f in [int(k) for k in meas] if 500 <= f <= 4000]
print("spread 500 Hz to 4 kHz: measured", round(max(selm) - min(selm), 1), "dB, predicted", round(max(sel) - min(sel), 1), "dB")
def q14(v): return int(round(v * 16384))
out = ["/* Generated by fit_eq.py from the measured response; Q14 biquads b0 b1 b2 a1 a2 at 16 kHz. */"]
for nm, chain in (("eq", eq), ("bass_lp", bass), ("harm_bp", harm)):
    out.append(f"static const int32_t {nm}_q14[{len(chain)}][5] = {{")
    for b, a in chain: out.append("  {" + ", ".join(str(q14(v)) for v in (b[0], b[1], b[2], a[1], a[2])) + "},")
    out.append("};")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
