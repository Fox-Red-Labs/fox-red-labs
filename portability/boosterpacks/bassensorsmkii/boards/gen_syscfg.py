#!/usr/bin/env python3
"""Write boards/<board>/bassens.syscfg from one pin table (BoosterPack pin -> MCU pin from TI's LaunchPad board files).
    9 SCL   10 SDA   6 HDC2080 power   24 DRV5055 power   27 OPT3001 power   28 TMP117 power   2 DRV5055 output (ADC)
Run: python3 gen_syscfg.py"""
import os
# id: (cli device, cli package, v2 device, scl, sda, hdc, drv, opt, tmp, adc pin or None, adc channel, uart rx, uart tx, uart instance or None)
BOARDS = {
    "mspm0g5187": ("MSPM0G518X", "LQFP-64(PM)", "MSPM0G5187", "PA9", "PA8", "PB22", "PB15", "PA15", "PA12", "PA25", 2, "PA11", "PA10", "UC0"),
    "mspm0g3519": ("MSPM0G351X", "LQFP-100(PZ)", "MSPM0G3519", "PC2", "PC3", "PA25", "PA26", "PB26", "PB27", "PA14", 12, "PA11", "PA10", None),
    "mspm33c321a": ("MSPM33C321A", "LQFP-100(PFA)", "MSPM33C321A", "PB13", "PB12", "PA22", None, None, None, None, 0, "PA11", "PA10", "UC12"),
}
for b, (dev, pkg, v2, scl, sda, hdc, drv, opt, tmp, adc, ch, rx, tx, uinst) in BOARDS.items():
    s = [f'''//@cliArgs --device "{dev}" --package "{pkg}" --part "Default"
//@v2CliArgs --device "{v2}" --package "{pkg}"
// @cliArgs --board /ti/boards/LP_{v2} --rtos nortos
// BP-BASSENSORSMKII on the LP-{v2}. Generated by boards/gen_syscfg.py; edit the table there.
// I2C controller 100 kHz on BoosterPack pins 9 (SCL) and 10 (SDA); four power-switch pins; DRV5055 output on ADC; backchannel UART 115200.
const Board  = scripting.addModule("/ti/driverlib/Board", {{}}, false);
const GPIO   = scripting.addModule("/ti/driverlib/GPIO", {{}}, false);
const I2C    = scripting.addModule("/ti/driverlib/I2C", {{}}, false);
const SYSCTL = scripting.addModule("/ti/driverlib/SYSCTL");
const UART   = scripting.addModule("/ti/driverlib/UART", {{}}, false);
''']
    if adc:
        s.append('const ADC12  = scripting.addModule("/ti/driverlib/ADC12", {}, false);\nconst ADC121 = ADC12.addInstance();')
    s.append('const I2C1   = I2C.addInstance();\nconst UART1  = UART.addInstance();')
    for n, p, init in (("HDC", hdc, "SET"), ("DRV", drv, "SET"), ("OPT", opt, None), ("TMP", tmp, None)):
        v = n.lower()
        if p is None:     # M33C321A: TI's board file puts pins 24, 27, 28 on PA16, PC5, PC4; SysConfig's LQFP-100(PFA) device data offers none of them as a GPIO
            continue
        seg = ''
        if b.startswith('mspm33'):   # MSPM33 SysConfig wants the port and its half named before it offers the pin
            num = int(p[2:])
            seg = f'\ng_{v}.port = "PORT{p[1]}";\ng_{v}.associatedPins[0].assignedPortSegment = "{"Lower" if num < 16 else "Upper"}";\ng_{v}.associatedPins[0].assignedPin = "{num}";'
        s.append(f'''const g_{v} = GPIO.addInstance();
g_{v}.$name = "{n}_PWR";''' + seg + f'''
g_{v}.associatedPins[0].$name = "{n}";
g_{v}.associatedPins[0].pin.$assign = "{p}";''' + (f'\ng_{v}.associatedPins[0].initialValue = "{init}";' if init else ''))
    if adc:
        s.append(f'''
ADC121.$name                       = "ADC12_0";
ADC121.sampClkSrc                  = "DL_ADC12_CLOCK_ULPCLK";
ADC121.sampClkDiv                  = "DL_ADC12_CLOCK_DIVIDE_8";
ADC121.sampleTime0                 = "125 us";
ADC121.powerDownMode               = "DL_ADC12_POWER_DOWN_MODE_MANUAL";
ADC121.adcMem0chansel              = "DL_ADC12_INPUT_CHAN_{ch}";
ADC121.peripheral.adcPin{ch}.$assign  = "{adc}";''')
    s.append(f'''
Board.peripheral.$assign          = "DEBUGSS";
Board.peripheral.swclkPin.$assign = "PA20";
Board.peripheral.swdioPin.$assign = "PA19";

I2C1.$name                     = "I2C";
I2C1.basicEnableController     = true;
I2C1.basicControllerBusSpeed   = 100000;
I2C1.peripheral.sdaPin.$assign = "{sda}";
I2C1.peripheral.sclPin.$assign = "{scl}";

UART1.$name                    = "UART_0";
UART1.enableFIFO               = true;
UART1.targetBaudRate           = 115200;''')
    if uinst:
        s.append(f'UART1.peripheral.$assign       = "{uinst}";')
    s.append(f'UART1.peripheral.rxPin.$assign = "{rx}";\nUART1.peripheral.txPin.$assign = "{tx}";\n')
    s.append('SYSCTL.forceDefaultClkConfig = true;\nSYSCTL.clockTreeEn           = true;\n' if b.startswith('mspm0') else 'SYSCTL.forceDefaultClkConfig = true;\nSYSCTL.peripheral.$assign    = "SYSCTL";\n')
    s.append('const ProjectConfig              = scripting.addModule("/ti/project_config/ProjectConfig", {}, false);\nProjectConfig.migrationCondition = true;\n')
    d = os.path.join(os.path.dirname(os.path.abspath(__file__)), b)
    os.makedirs(d, exist_ok=True)
    open(os.path.join(d, "bassens.syscfg"), "w").write("\n".join(s))
