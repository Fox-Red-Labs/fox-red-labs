#!/usr/bin/env python3
"""Generate the two MCU+ mapping headers between the AM263Px MCU+ SDK and the MMWAVE-L-SDK (IWRL6432), from the SDK headers.
  am263p_on_mmwave.h : force-included when an AM263Px example is built in a radar SDK project
  mmwave_on_am263p.h : force-included when a radar SDK example is built in an AM263Px project
What they hold: the EDMA functions the two SDKs spell differently (EDMACCPaRAMEntry_init vs EDMA_ccPaRAMEntry_init, read from
both edma.h files), a few macros one side lacks, and one behaviour fix (the watchdog: the AM263Px driver starts it in
Watchdog_open, the radar driver needs Watchdog_enable). Renames and small inline helpers only; nothing that needs logic
(GPIO banks against per-pin interrupts, the I2C transaction status field, SoC memory names and board functions stay listed as real differences).
  gen_compat.py <AM263Px SDK> <MMWAVE-L-SDK>"""
import glob, os, re, sys
AM, MM = sys.argv[1], sys.argv[2]
HERE = os.path.dirname(os.path.abspath(__file__))
def funcs(sdk):
    h = glob.glob(f"{sdk}/source/drivers/edma/v*/edma.h")[0]
    return set(re.findall(r"^\w+\s+(EDMA\w*)\s*\(", open(h).read(), re.M))
def norm(n):   # EDMACCPaRAMEntry_init, EDMA_ccPaRAMEntry_init, EDMA_InitParams_init, EDMA_initParamsInit -> one key
    return re.sub(r"[_]", "", n[4:]).lower()
am, mm = funcs(AM), funcs(MM)
am_k, mm_k = {norm(n): n for n in am}, {norm(n): n for n in mm}
pairs = sorted((am_k[k], mm_k[k]) for k in am_k.keys() & mm_k.keys() if am_k[k] != mm_k[k])
head = "/* Generated by gen_compat.py from the SDK headers (AM263Px MCU+ SDK 26.01.00.08, MMWAVE-L-SDK 05.05.04.02). Do not edit. */\n"
with open(os.path.join(HERE, "am263p_on_mmwave.h"), "w") as f:
    f.write(head + "#ifndef TIPORT_AM263P_ON_MMWAVE_H\n#define TIPORT_AM263P_ON_MMWAVE_H\n#include <stdint.h>\n#include <stddef.h>\n")
    f.write("/* The AM263Px drivers pull in the cache API through edma.h; the radar's do not, and its M4F calls are the same names. */\n#include <kernel/dpl/CacheP.h>\n")
    f.write("#ifndef CacheP_wbInv\n#define CacheP_wbInv(a, s, t) do { CacheP_wb((a), (s), (t)); CacheP_inv((a), (s), (t)); } while (0)\n#endif\n")
    f.write("#ifndef EDMA_PARAM_BIDX\n#define EDMA_PARAM_BIDX(val) ((val) & 0xFFFFU)\n#endif\n")
    f.write("#ifndef EDMA_PARAM_BIDX_EXT\n#define EDMA_PARAM_BIDX_EXT(val) (((val) & 0xFF0000U) >> 16)\n#endif\n")
    f.write("/* LIN data registers: same offsets on both chips (0x64, 0x74), different prefix. */\n"
            "#define CSL_LIN_LINRD0 CSL_APP_LIN_LINRD0\n#define CSL_LIN_LINTD0 CSL_APP_LIN_LINTD0\n")
    f.write("/* LIN global interrupt block: the AM263Px LIN has LIN_GLB_INT_EN and _CLR to gate its two interrupt lines; the radar's\n"
            "   LIN has no such registers (its lines go straight to the NVIC), so the calls have nothing to do there. Builds; the\n"
            "   interrupt path on the radar is not yet run. */\n"
            "typedef enum { LIN_INTERRUPT_LINE0 = 0U, LIN_INTERRUPT_LINE1 = 1U } LIN_InterruptLine;\n"
            "#define LIN_enableGlobalInterrupt(base, line) ((void)(base), (void)(line))\n"
            "#define LIN_disableGlobalInterrupt(base, line) ((void)(base), (void)(line))\n"
            "#define LIN_clearGlobalInterruptStatus(base, line) ((void)(base), (void)(line))\n")
    f.write(f"/* {len(pairs)} EDMA functions, AM263Px spelling -> radar spelling */\n")
    for a, m in pairs: f.write(f"#define {a} {m}\n")
    f.write("/* Watchdog: AM263Px code expects Watchdog_open to start the counter; the radar driver starts it in Watchdog_enable. */\n")
    f.write("#include <drivers/watchdog.h>\nstatic inline Watchdog_Handle tiport_Watchdog_open(uint8_t i, Watchdog_Params *p)\n"
            "{ Watchdog_Handle h = (Watchdog_open)(i, p); if (h != NULL) { Watchdog_enable(h); } return h; }\n#define Watchdog_open tiport_Watchdog_open\n#endif\n")
with open(os.path.join(HERE, "mmwave_on_am263p.h"), "w") as f:
    f.write(head + "#ifndef TIPORT_MMWAVE_ON_AM263P_H\n#define TIPORT_MMWAVE_ON_AM263P_H\n#include <stdint.h>\n")
    f.write(f"/* {len(pairs)} EDMA functions, radar spelling -> AM263Px spelling */\n")
    for a, m in pairs: f.write(f"#define {m} {a}\n")
    f.write("/* LIN data registers: same offsets on both chips, different prefix. */\n"
            "#define CSL_APP_LIN_LINRD0 CSL_LIN_LINRD0\n#define CSL_APP_LIN_LINTD0 CSL_LIN_LINTD0\n")
    f.write("/* Watchdog: the AM263Px driver already started the counter in Watchdog_open. */\n#define Watchdog_enable(h) ((void)(h))\n")
    f.write("/* I2C: the radar's ACCESS_ERROR has no AM263Px code. The other codes share names but not values on the two sides\n"
            "   (BUS_BUSY is -4 on AM263Px and -3 on the radar), so compare against the names, never against numbers. */\n"
            "#ifndef I2C_STS_ERR_ACCESS_ERROR\n#define I2C_STS_ERR_ACCESS_ERROR ((int32_t)-100) /* never returned by the AM263Px driver */\n#endif\n#endif\n")
print(len(pairs), "EDMA pairs;", "headers written")
