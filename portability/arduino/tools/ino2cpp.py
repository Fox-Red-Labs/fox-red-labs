#!/usr/bin/env python3
"""Turn an Arduino .ino into a .cpp the way the Arduino IDE does: add #include <Arduino.h> and
prototypes for every function defined at file scope, so a sketch can call a function defined below it.
Like the IDE, it finds the functions in the PREPROCESSED sketch (so #ifdef'd signatures are right).
Usage: CXX_CMD='tiarmclang <flags>' ino2cpp.py sketch.ino out.cpp
Other .ino files in the same folder are appended."""
import os, re, subprocess, sys, pathlib, tempfile, shlex

src = pathlib.Path(sys.argv[1]).resolve()
out = pathlib.Path(sys.argv[2])
files = [src] + sorted(p for p in src.parent.glob("*.ino") if p != src)
text = "".join(p.read_text() + "\n" for p in files)

# 1. preprocess "#include <Arduino.h> + sketch" and keep only the lines that come from the sketch itself
tmp = pathlib.Path(tempfile.mkdtemp()) / "sketch_pp.cpp"
tmp.write_text('#include <Arduino.h>\n#line 1 "SKETCH"\n' + text)
cmd = shlex.split(os.environ["CXX_CMD"]) + ["-E", "-x", "c++", str(tmp)]
pp = subprocess.run(cmd, capture_output=True, text=True, check=True).stdout
mine, cur = [], None
for line in pp.splitlines():
    m = re.match(r'#\s+\d+\s+"([^"]*)"', line)
    if m:
        cur = m.group(1)
        continue
    if cur == "SKETCH":
        mine.append(line)
body = "\n".join(mine)

# 2. function definitions at column 0: "<type> name(args)" then "{" on this or the next line
pat = re.compile(r'^(?!\s|#)((?:static\s+|inline\s+|extern\s+)*[A-Za-z_][\w:<>\s\*&]*?[\s\*&]([A-Za-z_]\w*)\s*\(([^;{}()]*(?:\([^)]*\)[^;{}()]*)*)\))\s*(?:__attribute__\(\(.*?\)\)\s*)?(?:\{|\n\s*\{)', re.M)
protos, names = [], []
for m in pat.finditer(body):
    name = m.group(2)
    if name in ("if", "while", "for", "switch", "return", "sizeof", "main"):
        continue
    protos.append(" ".join(m.group(1).split()) + ";")
    names.append(name)

# 3. insert the prototypes before the first function in the original text
first = len(text)
for n in names:
    m = re.search(r'^(?:static\s+|inline\s+)*[A-Za-z_][\w:<>\s\*&]*?[\s\*&]' + re.escape(n) + r'\s*\(', text, re.M)
    if m:
        first = min(first, m.start())
lineno = text[:first].count("\n") + 1
res = ('#include <Arduino.h>\n#line 1 "%s"\n' % src) + text[:first] + \
      "/* prototypes generated by ino2cpp.py */\n" + "\n".join(protos) + \
      '\n#line %d "%s"\n' % (lineno, src) + text[first:]
out.write_text(res)
