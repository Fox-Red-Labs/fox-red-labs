#!/usr/bin/env python3
"""Make the voice front-end test signal as C arrays: far-end speech-like noise, its echo through a fixed room impulse
response at four mics with small fractional delays, and near-end noise. Deterministic (fixed seed, numpy).
  python3 -I gen_signal.py <out dir> [--seconds 4]
Writes <out>/fe_data.c, <out>/fe_data.h, and for the host check <out>/sig.npz (far, mic, echo-only and noise-only mic
signals, the impulse response). The clip is built circularly (circular convolution and delays), so looping it plays one
continuous periodic signal with no seam. Prints the SHA-256 of fe_data.c."""
import argparse, hashlib, os
import numpy as np

FS = 16000
NEAR_DELAYS = [0.0, 1.25, 2.5, 3.75]   # samples: a talker off to one side of a 4-mic line, about 2.7 cm spacing at 16 kHz
ECHO_DELAYS = [0.6, 0.2, 0.4, 0.8]     # speaker under the array: the echo reaches the mics almost together
TAPS = 16; TAP_DELAY = 4.0             # beamformer FIR: integer bulk delay plus the steering fraction


def frac_delay_circ(x, d):
    X = np.fft.rfft(x); k = np.arange(X.size)
    return np.fft.irfft(X * np.exp(-2j * np.pi * k * d / x.size), x.size)


def speech_like(rng, n):
    """White noise through formant resonators that change every syllable, times a syllable envelope with pauses."""
    out = np.zeros(n); vowels = [(700, 1200, 2600), (300, 2300, 3000), (500, 1000, 2400), (400, 1900, 2550), (350, 800, 2300)]
    i = 0
    while i < n:
        syl = int(rng.uniform(0.12, 0.28) * FS); gap = int(rng.uniform(0.04, 0.30) * FS)
        seg = rng.standard_normal(syl + 400)
        y = np.zeros_like(seg)
        for f, bw in zip(vowels[rng.integers(len(vowels))], (80, 120, 160)):
            r = np.exp(-np.pi * bw / FS); th = 2 * np.pi * f / FS
            a1, a2 = 2 * r * np.cos(th), -r * r; z1 = z2 = 0.0; o = np.empty_like(seg)
            for j, s in enumerate(seg):
                v = s + a1 * z1 + a2 * z2; z2, z1 = z1, v; o[j] = v
            y += o / np.std(o)
        y = y[400:]
        env = np.sin(np.pi * np.arange(syl) / syl) ** 0.7 * rng.uniform(0.4, 1.0)
        m = min(syl, n - i); out[i:i + m] = (y * env)[:m]
        i += syl + gap
    return out


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("out"); ap.add_argument("--seconds", type=float, default=4.0)
    a = ap.parse_args(); os.makedirs(a.out, exist_ok=True)
    rng = np.random.default_rng(20261026)
    n = int(a.seconds * FS); n -= n % 160
    far = speech_like(rng, n)
    far *= 3000.0 / np.sqrt(np.mean(far ** 2))           # RMS 3000 of 32767 (about -21 dBFS), peaks under full scale
    far = np.clip(np.round(far), -32768, 32767)
    # Room impulse response: 2 ms direct path, then an exponential tail (time constant 30 ms), 190 ms long (fits 200 ms),
    # scaled so the echo is 6 dB below the far-end signal.
    L = 3040; h = np.zeros(L); h[32] = 0.6
    t = np.arange(L); tail = rng.standard_normal(L) * np.exp(-t / (0.030 * FS)) * 0.04; tail[:40] = 0; h += tail
    echo = np.fft.irfft(np.fft.rfft(far) * np.fft.rfft(h, n), n)
    g = 1500.0 / np.sqrt(np.mean(echo ** 2)); h *= g; echo *= g   # echo RMS 1500 at the mics
    near_src = np.convolve(rng.standard_normal(n + 64), np.ones(8) / 8, mode="same")[32:32 + n]   # low-passed noise, a fan in the room
    near_src *= 30.0 / np.sqrt(np.mean(near_src ** 2))
    mic = np.zeros((n, 4)); mic_echo = np.zeros((n, 4)); mic_noise = np.zeros((n, 4))
    for k in range(4):
        e = frac_delay_circ(echo, ECHO_DELAYS[k]); s = frac_delay_circ(near_src, NEAR_DELAYS[k]) + rng.standard_normal(n) * 20.0
        mic_echo[:, k] = e; mic_noise[:, k] = s; mic[:, k] = e + s
    mic16 = np.clip(np.round(mic), -32768, 32767).astype(np.int16)
    far16 = far.astype(np.int16)
    # Beamformer taps: delay channel k by TAP_DELAY + (max near delay - its near delay), Blackman-windowed sinc, DC gain 1.
    taps = np.zeros((4, TAPS), dtype=np.int16)
    for k in range(4):
        d = TAP_DELAY + max(NEAR_DELAYS) - NEAR_DELAYS[k]; j = np.arange(TAPS)
        hk = np.sinc(j - d) * np.blackman(TAPS + 2)[1:-1]; hk /= hk.sum()
        taps[k] = np.round(hk * 32768).clip(-32768, 32767)
    np.savez(os.path.join(a.out, "sig.npz"), far=far16, mic=mic16, mic_echo=mic_echo, mic_noise=mic_noise, h=h, taps=taps)
    with open(os.path.join(a.out, "fe_data.h"), "w") as f:
        f.write("/* Generated by portability/voice-fe/gen_signal.py; do not edit. */\n#ifndef FE_DATA_H\n#define FE_DATA_H\n#include <stdint.h>\n")
        f.write("#define FE_CLIP %d\nextern const int16_t fe_far[FE_CLIP];\nextern const int16_t fe_mic[FE_CLIP * 4];\nextern const int16_t fe_bf_taps[4][16];\n#endif\n" % n)
    def arr(v):
        v = [int(x) for x in v]; return ",\n".join(",".join(str(x) for x in v[i:i + 24]) for i in range(0, len(v), 24))
    c = ["/* Generated by portability/voice-fe/gen_signal.py (seed 20261026, %d samples at 16 kHz); do not edit. */" % n, '#include "fe_data.h"',
         "const int16_t fe_bf_taps[4][16] = {%s};" % ",".join("{%s}" % ",".join(str(int(x)) for x in r) for r in taps),
         "const int16_t fe_far[FE_CLIP] = {\n%s};" % arr(far16), "const int16_t fe_mic[FE_CLIP * 4] = {\n%s};" % arr(mic16.reshape(-1))]
    p = os.path.join(a.out, "fe_data.c"); open(p, "w").write("\n".join(c) + "\n")
    print("fe_data.c sha256 %s, %d samples, far rms %.0f, echo rms at mic 0 %.0f, noise rms at mic 0 %.1f, peak mic %d" % (
        hashlib.sha256(open(p, "rb").read()).hexdigest(), n, np.sqrt(np.mean(far16.astype(float) ** 2)), np.sqrt(np.mean(mic_echo[:, 0] ** 2)),
        np.sqrt(np.mean(mic_noise[:, 0] ** 2)), int(np.abs(mic16).max())))


main()
