#!/usr/bin/env python3
"""Make the 16 kB ROM image the build uses, and rom.h for the board.
  mkrom.py out.h out.bin [rom_file]
With a reader-supplied ROM file (16,384 bytes) it is used as is. Without one, a ROM-less test image is written: a tiny boot stub and a
Z80 program that fills the bitmap and then, every frame, rewrites all 768 attribute bytes. No Sinclair code is in it.
The program is hand-assembled here; the listing is in the comments."""
import sys
out_h, out_bin = sys.argv[1], sys.argv[2]
if len(sys.argv) > 3:
    rom = open(sys.argv[3], "rb").read()
    if len(rom) != 16384: sys.exit("ROM must be exactly 16384 bytes")
    kind = "reader ROM"
else:
    rom = bytearray(16384)
    rom[0x0000:0x0007] = bytes([0xF3, 0x31, 0x00, 0x00, 0xC3, 0x00, 0x01])   # DI ; LD SP,0 ; JP 0100
    rom[0x0038:0x003A] = bytes([0xFB, 0xC9])                                  # EI ; RET  (the 50 Hz interrupt handler)
    p = bytearray()
    p += bytes([0x21, 0x00, 0x40, 0x01, 0x00, 0x18])                          # LD HL,4000 ; LD BC,1800
    fill = len(p)
    p += bytes([0x7D, 0xAC, 0x77, 0x23, 0x0B, 0x78, 0xB1])                    # fill: LD A,L ; XOR H ; LD (HL),A ; INC HL ; DEC BC ; LD A,B ; OR C
    p += bytes([0x20, (fill - (len(p) + 2)) & 0xFF])                          # JR NZ,fill
    p += bytes([0xED, 0x56, 0xFB, 0x16, 0x00])                                # IM 1 ; EI ; LD D,0
    loop = len(p)
    p += bytes([0x76, 0x14, 0x21, 0x00, 0x58, 0x01, 0x00, 0x03])              # loop: HALT ; INC D ; LD HL,5800 ; LD BC,0300
    f2 = len(p)
    p += bytes([0x7A, 0x85, 0xE6, 0x7F, 0xF6, 0x01, 0x77, 0x23, 0x0B, 0x78, 0xB1])  # f2: LD A,D ; ADD A,L ; AND 7F ; OR 01 ; LD (HL),A ; INC HL ; DEC BC ; LD A,B ; OR C
    p += bytes([0x20, (f2 - (len(p) + 2)) & 0xFF])                            # JR NZ,f2
    p += bytes([0x18, (loop - (len(p) + 2)) & 0xFF])                          # JR loop
    rom[0x0100:0x0100 + len(p)] = p
    rom = bytes(rom); kind = "ROM-less test image"
open(out_bin, "wb").write(rom)
open(out_h, "w").write("/* generated by mkrom.py: %s */\n#include <stdint.h>\nstatic const uint8_t zx_rom[16384] = {%s};\n" % (kind, ",".join(str(b) for b in rom)))
print(kind)
