#!/usr/bin/env python3
"""Write roms.h (C arrays) from ROM files: mkroms.py out.h rom.ch8 ... Names drop the extension."""
import sys, os, glob
out, files = sys.argv[1], [f for a in sys.argv[2:] for f in glob.glob(a)]
files = sorted(set(files), key=lambda f: os.path.basename(f))
if not files: sys.exit("no ROMs found: run tools/fetch_tests.sh or put .ch8 files in ports/chip8/roms/")
h = ["/* generated by mkroms.py */", "#include <stdint.h>"]
for i, f in enumerate(files):
    d = open(f, "rb").read()
    h.append("static const uint8_t rom_%d[] = {%s};" % (i, ",".join(str(b) for b in d)))
h.append("#define ROM_COUNT %d" % len(files))
h.append("static const uint8_t *const rom_data[] = {%s};" % ",".join("rom_%d" % i for i in range(len(files))))
h.append("static const unsigned rom_len[] = {%s};" % ",".join(str(os.path.getsize(f)) for f in files))
h.append("static const char *const rom_names[] = {%s};" % ",".join('"%s"' % os.path.splitext(os.path.basename(f))[0][:22] for f in files))
open(out, "w").write("\n".join(h) + "\n")
