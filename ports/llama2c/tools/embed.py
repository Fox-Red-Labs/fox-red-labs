#!/usr/bin/env python3
"""Write a C file holding the int8 checkpoint and the tokenizer as read-only, 4-byte-aligned arrays (they land in flash).
  python3 -I embed.py model_q80.bin tok512.bin out.c"""
import sys
def arr(name, path):
    b = open(path, 'rb').read()
    rows = ',\n'.join(', '.join('0x%02x' % c for c in b[i:i + 24]) for i in range(0, len(b), 24))
    return f"const unsigned char {name}[{len(b)}] __attribute__((aligned(4))) = {{\n{rows}\n}};\nconst unsigned int {name}_len = {len(b)};\n"
open(sys.argv[3], 'w').write("/* generated by embed.py */\n" + arr('ll_model_blob', sys.argv[1]) + arr('ll_tok_blob', sys.argv[2]))
