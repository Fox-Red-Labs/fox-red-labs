#!/usr/bin/env python3
"""Turn a hosts file (or a plain list of domains) into the sorted 40-bit hash table the DNS sinkhole searches.

  python3 gen_blocklist.py hosts.txt -o blocklist.bin                  # table: 5 bytes per domain, sorted, big-endian
  python3 gen_blocklist.py hosts.txt -o blocklist.bin --c-array b.h    # same table as a C array, for builds without .incbin
  python3 gen_blocklist.py hosts.txt -o blocklist.bin --pad-to 200000  # add random keys up to N entries (size tests only)
  python3 gen_blocklist.py --check blocklist.bin ads.example.com       # is this name in the table?

Hash: 64-bit FNV-1a over the lower-case dotted name without a trailing dot, folded to 40 bits as
(h ^ (h >> 40)) & 0xFFFFFFFFFF. The firmware uses the same function (firmware/dns_sinkhole.c).
At 40 bits a name that is not on the list matches a stored key with probability N / 2^40, so about
7e-8 per query for 80,000 domains. Input: lines of "0.0.0.0 name" or "127.0.0.1 name" (hosts format) or a bare name;
# starts a comment. localhost-type names are skipped.
"""
import argparse, random, re, sys

FNV_OFF, FNV_PRIME, M64 = 0xCBF29CE484222325, 0x100000001B3, (1 << 64) - 1
NAME_RE = re.compile(r"^(?=.{1,253}$)([a-z0-9_]([a-z0-9_-]{0,61}[a-z0-9_])?)(\.[a-z0-9_]([a-z0-9_-]{0,61}[a-z0-9_])?)+$")
SKIP = {"localhost", "localhost.localdomain", "local", "broadcasthost", "ip6-localhost", "ip6-loopback", "ip6-localnet",
        "ip6-mcastprefix", "ip6-allnodes", "ip6-allrouters", "ip6-allhosts", "0.0.0.0"}


def key40(name: str) -> int:
    h = FNV_OFF
    for b in name.lower().rstrip(".").encode("ascii"):
        h = ((h ^ b) * FNV_PRIME) & M64
    return (h ^ (h >> 40)) & 0xFFFFFFFFFF


def names(path):
    seen = set()
    for line in open(path, encoding="utf-8", errors="replace"):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        n = parts[1] if parts[0] in ("0.0.0.0", "127.0.0.1", "::1", "::") and len(parts) > 1 else parts[0]
        n = n.lower().rstrip(".")
        if n in SKIP or not NAME_RE.match(n) or re.fullmatch(r"[0-9.]+", n):
            continue
        seen.add(n)
    return seen


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("src", nargs="*", help="hosts file or domain list; with --check: the table, then names")
    ap.add_argument("-o", "--out", help="table file to write")
    ap.add_argument("--c-array", help="also write the table as a C array to this header")
    ap.add_argument("--limit", type=int, help="keep only the first N names after sorting by key (size tests)")
    ap.add_argument("--pad-to", type=int, help="add random keys until the table has N entries (size tests only)")
    ap.add_argument("--check", action="store_true", help="look names up in an existing table")
    a = ap.parse_args()
    if a.check:
        data = open(a.src[0], "rb").read()
        keys = {int.from_bytes(data[i:i + 5], "big") for i in range(0, len(data), 5)}
        for n in a.src[1:]:
            print(f"{n}: key {key40(n):010x} {'BLOCKED' if key40(n) in keys else 'not in table'}")
        return
    if not a.src or not a.out:
        ap.error("need a source file and -o")
    ns = set()
    for s in a.src:
        ns |= names(s)
    keys = sorted({key40(n) for n in ns})
    collisions = len(ns) - len(keys)
    if a.limit:
        keys = keys[:a.limit]
    if a.pad_to and len(keys) < a.pad_to:
        rnd = random.Random(1)
        ks = set(keys)
        while len(ks) < a.pad_to:
            ks.add(rnd.getrandbits(40))
        keys = sorted(ks)
    with open(a.out, "wb") as f:
        for k in keys:
            f.write(k.to_bytes(5, "big"))
    if a.c_array:
        with open(a.c_array, "w") as f:
            f.write("/* Generated by gen_blocklist.py. %d entries of 5 bytes, sorted, big-endian. */\n" % len(keys))
            f.write("const unsigned char blk_table[%d] = {\n" % (5 * len(keys) or 1))
            for i in range(0, len(keys), 4):
                f.write(",".join("0x%02x" % b for k in keys[i:i + 4] for b in k.to_bytes(5, "big")) + ",\n")
            f.write("};\nconst unsigned int blk_table_bytes = %d;\n" % (5 * len(keys)))
    print(f"{len(ns)} names, {len(keys)} keys, {collisions} 40-bit collisions dropped, {5 * len(keys)} bytes -> {a.out}", file=sys.stderr)


if __name__ == "__main__":
    main()
