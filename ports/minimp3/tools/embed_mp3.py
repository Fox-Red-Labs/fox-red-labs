#!/usr/bin/env python3 -I
"""Write a C file holding the two test clips as read-only, 4-byte-aligned arrays (they land in flash).
  embed_mp3.py stereo128.mp3 mono64.mp3 out.c"""
import sys
def arr(name, path):
    b = open(path, 'rb').read()
    rows = ',\n'.join(', '.join('0x%02x' % c for c in b[i:i + 24]) for i in range(0, len(b), 24))
    return f"const unsigned char {name}[{len(b)}] __attribute__((aligned(4))) = {{\n{rows}\n}};\nconst unsigned int {name}_len = {len(b)};\n"
open(sys.argv[3], 'w').write("/* generated by embed_mp3.py */\n" + arr('mp3_clip_stereo', sys.argv[1]) + arr('mp3_clip_mono', sys.argv[2]))
