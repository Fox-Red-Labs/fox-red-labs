const uint8_t *font_glyph(char c)
{
    if (c >= '0' && c <= '9') return F[1 + (c - '0')];
    if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
    if (c >= 'A' && c <= 'Z') return F[11 + (c - 'A')];
    if (c == ':') return F[37];
    if (c == '!') return F[38];
    if (c == '-') return F[39];
    if (c == '/') return F[40];
    return F[0];
}
