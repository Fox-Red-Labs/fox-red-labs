#!/usr/bin/env python3
"""Write test_data_c28.h from upstream/BitNetMCU_MNIST_test_data.h for the C28x.
Upstream writes the int8 pixels as hex bytes (0xEC). On an 8-bit-char machine 0xEC stored in int8_t
reads back as -20; on the C28x int8_t is 16 bits (c28_int8.h), so it would read 236. This rewrites
each hex byte as the signed value an 8-bit machine reads (0xEC -> -20) and makes the arrays const
(so they stay in flash, as bitnet_run.c does for the MSPM0). Nothing else changes."""
import re, sys, os
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, "upstream", "BitNetMCU_MNIST_test_data.h")).read()
def s8(m):
    v = int(m.group(0), 16)
    return str(v - 256 if v > 127 else v)
out = re.sub(r"0x[0-9A-Fa-f]{2}\b", s8, src)
out = re.sub(r"^(u?int8_t )", r"const \1", out, flags=re.M)
hdr = "/* Generated by make_test_data.py from upstream/BitNetMCU_MNIST_test_data.h (BitNetMCU, GPL-3.0): hex bytes as signed values, arrays const. */\n"
open(os.path.join(here, "test_data_c28.h"), "w").write(hdr + out)
print("test_data_c28.h:", out.count("const int8_t"), "digits,", out.count("const uint8_t"), "labels")
