// Turns app.wat into app.wasm and app_wasm.h (a C byte array). Needs the npm package "wabt":
//   mkdir -p /tmp/wabt && cd /tmp/wabt && npm init -y && npm install wabt   (5 MB)
//   NODE_PATH=/tmp/wabt/node_modules node app/build_app.js
const fs = require('fs'), path = require('path');
const wabt = require('wabt');
(async () => {
  const w = await wabt();
  const src = fs.readFileSync(path.join(__dirname, 'app.wat'), 'utf8');
  const m = w.parseWat('app.wat', src);
  m.validate();
  const { buffer } = m.toBinary({ log: false, write_debug_names: false });
  fs.writeFileSync(path.join(__dirname, 'app.wasm'), buffer);
  let h = '// Generated by app/build_app.js from app.wat. Do not edit.\n#include <stdint.h>\nstatic const uint8_t app_wasm[] = {';
  buffer.forEach((b, i) => { h += (i % 16 ? ' ' : '\n  ') + '0x' + b.toString(16).padStart(2, '0') + ','; });
  h += '\n};\nstatic const unsigned app_wasm_len = ' + buffer.length + ';\n';
  fs.writeFileSync(path.join(__dirname, 'app_wasm.h'), h);
  console.log('app.wasm', buffer.length, 'bytes');
})();
