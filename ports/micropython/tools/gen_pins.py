#!/usr/bin/env python3
"""Write boards/pins_<dev>.h: the IOMUX index (PINCM number minus 1) of every GPIO pin.

Source: the device data that ships with SysConfig (deviceData/<DEV>/<DEV>.json), the same
table SysConfig uses to write ti_msp_dl_config.h. 0 in the table means the pin does not exist
on the package (index 0 is PINCM1, which is why the table stores PINCM and the code subtracts 1).
Usage: gen_pins.py <SysConfig dist dir> (default /Applications/ti/sysconfig_1.28.0/dist)
"""
import json, re, sys, pathlib
dist = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "/Applications/ti/sysconfig_1.28.0/dist")
out = pathlib.Path(__file__).resolve().parent.parent / "boards"
for dev, tag in (("MSPM0G351X", "g3519"), ("MSPM0G350X", "g3507"), ("MSPM0G518X", "g5187")):
    d = json.load(open(dist / "deviceData" / dev / f"{dev}.json"))
    t = {}
    for p in d["devicePins"].values():
        m = re.fullmatch(r"P([ABC])(\d+)", p["name"])
        pc = p["attributes"].get("iomux_pincm")
        if m and pc not in (None, "None"):
            t[(m[1], int(m[2]))] = int(pc)
    lines = [f"// Generated by tools/gen_pins.py from the SysConfig device data for {dev}. Do not edit.",
             "// Each entry is the PINCM number (1 to 255); 0 means the pin is not on this package."]
    for port in "ABC":
        row = ", ".join(str(t.get((port, n), 0)) for n in range(32))
        lines.append(f"static const uint8_t frl_pincm_{port.lower()}[32] = {{ {row} }};")
    (out / f"pins_{tag}.h").write_text("\n".join(lines) + "\n")
    print(tag, len(t), "pins")
