#!/usr/bin/env python3
"""Write fir_hb.h and print the whole input filter's response.

The wake-word input path takes the I2S rate 47,619 Hz to 7,936.5 Hz (the nearest whole division to the
model's 8 kHz) with no multiplier in the fast part, because the chip's Cortex-M0+ multiplies in about 30
cycles and a 60-tap filter at the I2S rate used half the CPU (measured: 44,000 cycles per 1 ms interrupt):
  stage 1: CIC (running-sum) filter, order 4, decimate by 3, 47,619 -> 15,873 Hz: adds only
  stage 2: 31-tap half-band FIR, decimate by 2, 15,873 -> 7,936.5 Hz: 8 multiplies per output
"""
import numpy as np, sys
FS = 32e6 / 7 / 96; FS2 = FS / 3
N = 31
n = np.arange(N) - (N - 1) // 2
h = 0.5 * np.sinc(n / 2) * np.blackman(N + 2)[1:-1]
h[n == 0] = 0.5
h /= h.sum()
q = np.round(h * 32768).astype(int)
ks = list(range(1, 16, 2))
coef = [int(q[(N - 1) // 2 + k]) for k in ks]
f = np.linspace(1, FS / 2, 20000)
cic = np.abs(np.sin(np.pi * f * 3 / FS) / (3 * np.sin(np.pi * f / FS))) ** 4
hb = np.abs(np.exp(-2j * np.pi * np.outer(f, np.arange(N)) / FS2) @ (q / 32768))
H = cic * hb
db = lambda fr: 20 * np.log10(H[np.argmin(abs(f - fr))])
print(f"in {FS:.1f} Hz, out {FS/6:.1f} Hz; total gain at 300 Hz {db(300):.2f} dB, 1 kHz {db(1000):.2f}, 2 kHz {db(2000):.2f}, 3 kHz {db(3000):.2f}, 3.5 kHz {db(3500):.2f}, 4 kHz {db(4000):.1f}")
fold = (f > FS / 6 - 3500) & (f < FS / 6 + 3500) | (f > 2 * FS / 6 - 3500) & (f < 2 * FS / 6 + 3500)
print(f"worst gain in the bands that fold into 0 to 3.5 kHz: {20*np.log10(H[fold & (f > 4400)].max()):.1f} dB; coefficients {coef}")
out = sys.argv[1] if len(sys.argv) > 1 else "fir_hb.h"
open(out, "w").write("/* Generated by make_fir2.py: half-band decimate-by-2, Q15, taps at +-1, 3, ..., 15 around a centre of 0.5. */\n"
                     "#define HB_N 31\n#define HB_K 8\nstatic const int16_t hb_q15[HB_K] = { %s };\n" % ", ".join(map(str, coef)))
