#!/usr/bin/env python3
"""Write fe_tables.h for the board from features.py, so the two share one set of constants."""
import sys, os
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import features as F
w = np.round(F.WIN * 32767).astype(int)
out = sys.argv[1] if len(sys.argv) > 1 else "fe_tables.h"
open(out, "w").write(f"""/* Generated by host/gen_tables.py from host/features.py (the specification). Do not edit. */
#define FE_NFFT {F.NFFT}
#define FE_FRAME {F.FRAME}
#define FE_T {F.T}
#define FE_C {F.C}
#define FE_DF {F.DF:.6f}f
#define FE_REF_FLOOR_DB {F.REF_FLOOR_DB:.1f}f
static const uint16_t fe_band_bins[10] = {{ {", ".join(map(str, F.BAND_BINS))} }};
static const uint16_t fe_peak_bins[2] = {{ {F.PEAK_BINS[0]}, {F.PEAK_BINS[1]} }};
static const int16_t fe_win_q15[{F.NFFT}] = {{ {", ".join(map(str, w))} }};
""")
print("wrote", out, "bands", F.BAND_BINS, "peak", F.PEAK_BINS)
