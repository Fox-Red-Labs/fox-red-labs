#!/usr/bin/env python3
"""Write fir_dec3.h: the low-pass filter the board runs before keeping every third sample
(47,619 Hz in, 15,873 Hz out). Windowed sinc, numpy only. Coefficients in Q12 so the board can
multiply 18-bit samples in 32 bits without overflow (60 taps, sum of |c| about 1.4)."""
import numpy as np, sys
FS_IN = 32e6 / 7 / 96          # I2S word clock: SYSOSC 32 MHz / bclk divider 7 / 96 bits per frame
TAPS, CUT = 60, 6300.0
n = np.arange(TAPS) - (TAPS - 1) / 2
h = np.sinc(2 * CUT / FS_IN * n) * np.blackman(TAPS)
h /= h.sum()
q = np.round(h * 4096).astype(int)
q[TAPS // 2] += 4096 - q.sum()           # unity gain at DC after rounding
f = np.linspace(0, FS_IN / 2, 2048)
H = np.abs(np.exp(-2j * np.pi * np.outer(f, np.arange(TAPS)) / FS_IN) @ (q / 4096))
db = lambda fr: 20 * np.log10(H[np.argmin(abs(f - fr))])
print(f"fs_in {FS_IN:.1f} Hz, out {FS_IN/3:.1f} Hz; gain at 3 kHz {db(3000):.2f} dB, 6 kHz {db(6000):.2f}, "
      f"7.9 kHz {db(7900):.1f}, worst alias above 9.6 kHz (lands above 6.3 kHz) {20*np.log10(H[f > 9600].max()):.1f} dB; sum|c| {abs(q).sum()/4096:.3f}")
out = sys.argv[1] if len(sys.argv) > 1 else "fir_dec3.h"
open(out, "w").write("/* Generated by host/make_fir.py: decimate-by-3 low-pass, Q12, %d taps. */\n#define FIR_TAPS %d\n"
                     "static const int16_t fir_q12[FIR_TAPS] = { %s };\n" % (TAPS, TAPS, ", ".join(map(str, q))))
