#!/usr/bin/env python3
"""Turn any photo into a C array the G3507 can hold: 160x240 RGB565 (75 kB), drawn 2x on
the 320x480 screen. Crops to fill the portrait screen. Output goes to private/ (git-ignored):
personal photos never enter the repo.

  photo.py <image>         photo: 160x240, 65,536 colors, each pixel drawn 2x2
  photo.py --pal16 <image> graphics and text: full 320x480, 16 colors (75 kB), sharp edges
  --name <n>               save as a named screen (default "photo")
Each screen is saved as private/screens/<n>.h; ./build.sh builds out/screen_<n>/screen_<n>.out
for every saved screen.
"""
import os, sys
from PIL import Image, ImageOps

NAME = "photo"
if "--name" in sys.argv:
    k = sys.argv.index("--name"); NAME = sys.argv[k + 1]; del sys.argv[k:k + 2]
PAL = sys.argv[1] == "--pal16"
if PAL:
    sys.argv.pop(1)
W, H = (320, 480) if PAL else (160, 240)
src = ImageOps.exif_transpose(Image.open(sys.argv[1])).convert("RGB")
if src.width > src.height:          # landscape photo: turn it to fill the portrait screen
    src = src.rotate(90, expand=True)
im = ImageOps.fit(src, (W, H), Image.Resampling.LANCZOS)
here = os.path.dirname(os.path.abspath(__file__))
os.makedirs(os.path.join(here, "private", "screens"), exist_ok=True)
with open(os.path.join(here, "private", "screens", NAME + ".h"), "w") as f:
    f.write(f"/* generated by photo.py from {os.path.basename(sys.argv[1])} */\n#include <stdint.h>\n")
    f.write(f"#define PHOTO_W {W}\n#define PHOTO_H {H}\n")
    f.write("static const uint16_t photo_unused[1] = {0,\n" if PAL else f"static const uint16_t photo[{W * H}] = {{\n")
    if PAL:
        q = im.quantize(16, dither=Image.Dither.NONE)
        pal = q.getpalette()[:48]
        f.write("};\n#define PHOTO_PAL16 1\n")
        f.write("static const uint16_t photo_pal[16] = {" + ",".join(
            f"0x{((pal[3*i] >> 3) << 11) | ((pal[3*i+1] >> 2) << 5) | (pal[3*i+2] >> 3):04X}"
            for i in range(16)) + "};\n")
        idx = list(q.tobytes())
        f.write(f"static const uint8_t photo4[{W * H // 2}] = {{\n")
        for i in range(0, len(idx), 32):
            f.write(",".join(str((idx[j] << 4) | idx[j + 1]) for j in range(i, i + 32, 2)) + ",\n")
        f.write("};\n")
        q.convert("RGB").save(os.path.join(here, "private", "screens", NAME + "-preview.png"))
        print(f"wrote private/screens/{NAME}.h ({W}x{H}, 16 colors, {W * H // 2} bytes)")
        sys.exit(0)
    px = list(im.getdata())
    for i in range(0, len(px), 16):
        f.write(",".join(f"0x{((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3):04X}"
                         for r, g, b in px[i:i + 16]) + ",\n")
    f.write("};\n")
im.resize((W * 2, H * 2), Image.Resampling.NEAREST).save(os.path.join(here, "private", "screens", NAME + "-preview.png"))
print(f"wrote private/screens/{NAME}.h ({W}x{H}, {W * H * 2} bytes)")
