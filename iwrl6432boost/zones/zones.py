def build_cfg(z, base=BASECFG):
    out = ["% PresenceDetect-zones.cfg: generated by iwrl6432boost/zones/zones.py from zones.json. Do not edit by hand.",
           "% It is PresenceDetect-hold12.cfg (TI's PresenceDetect.cfg with minor2emptyThre 12 and lowPowerCfg 0) with the four mpdBoundaryBox lines replaced.",
           "% mpdBoundaryBox <zone> <xMin> <xMax> <yMin> <yMax> <zMin> <zMax>. The demo ignores the zone number and numbers the boxes in the order sent; it reads only x and y."]
    hw = z["x_half_width_m"]; seen_banner = False
    for line in open(base):
        l = line.rstrip("\n")
        if l.startswith("mpdBoundaryBox"):
            if not any(o.startswith("mpdBoundaryBox") for o in out):
                for i, zz in enumerate(z["zones"], 1):
                    out.append(f"% zone {i}: {zz['name']}")
                    out.append(f"mpdBoundaryBox {i} {-hw} {hw} {zz['y_min']} {zz['y_max']} 0 3")
            continue
        if l.startswith("%") and not seen_banner and not l.startswith("% ****"): continue
        if l.startswith("% ****"): seen_banner = True
        out.append(l)
    return "\n".join(out) + "\n"

# ------------------------------------------------------------------ decode
def decode_zones(tl):
    """TLV list -> (states list, peak_m or None, nobj_hint). states is None if no 315."""
    from radar_link import decode
    d = decode(tl)
    peak = None
    if d["prof"]:
        p = d["prof"]
        i = max(range(len(p)), key=lambda k: p[k])
        peak = round(i * M_PER_BIN, 2) if p[i] > 0 else None
    return (d["zones"] if d["nz"] else None), peak

