def check(path, cuefile=None):
    """Per-zone detect (first on after the 'go' cue) and clear (off after the 'leave' cue) times, from a frame log."""
    rows = list(csv.reader(open(path))); hdr = rows[0]; zi = [i for i, h in enumerate(hdr) if h.startswith("z_")]
    cues = json.load(open(cuefile)) if cuefile else {}
    t = [float(r[0]) for r in rows[1:]]
    out = {}
    for i in zi:
        name = hdr[i][2:]; v = [int(r[i]) for r in rows[1:]]
        ons = [t[k] for k in range(len(v)) if v[k] and (k == 0 or not v[k - 1])]
        offs = [t[k] for k in range(len(v)) if not v[k] and k and v[k - 1]]
        o = {"on_times": [round(x - cues.get("at_door", t[0]), 1) for x in ons], "off_times": [round(x - cues.get("at_door", t[0]), 1) for x in offs],
             "frames_on": sum(1 for x in v if x)}
        if "leave" in cues: o["clear_after_leave_cue_s"] = [round(x - cues["leave"], 1) for x in offs if x >= cues["leave"]][:1]
        out[name] = o
    print(json.dumps(out, indent=1)); return out


