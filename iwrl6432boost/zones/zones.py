#!/usr/bin/env python3
"""Room zones from the shipped Motion and Presence Detection demo on the IWRL6432BOOST. No reflash.

  zones.py cfg                      write cfg/PresenceDetect-zones.cfg from zones.json (the hold-12 config with our boxes)
  zones.py apply                    reset the radar (xds110reset), send that cfg over the CLI, check frames flow (one start per boot)
  zones.py run [--seconds N] [--label L] [--html live/index.html] [--no-apply-check]
                                    stream frames, print and log zone changes, write the live page once a second
  zones.py walk                     the scripted walk-through (door, desk, sit, out): posts ONE dashboard ask, then speaks the cues
  zones.py check LOG [--cues]       read a frame log and print per-zone detect and clear times against the cues
  zones.py replay CSV...            run recorded eval frames (iwrl6432boost/eval/results/*.csv, the shipped four boxes) through the tracker
  zones.py selftest                 no radar: decoder, tracker, page and the Home Assistant poster against a local mock

Python 3 + pyserial (use ~/.venvs/iwrl6432/bin/python). Needs the radar's port free: take the lock first
(the script takes and drops the folder $TMPDIR/iwrl6432boost.lock).

Zone state in TLV 315: byte 0 is the zone count, then 2 bits a zone from the low bit: 0 empty, 1 minor motion (a still person's
breathing or typing), 2 major motion (walking). Read from mpdproc.c in the SDK (STATE_EMPTY 0, STATE_MINOR 1, STATE_MAJOR 2).
A zone is "occupied" when its value is not 0.
Home Assistant posting is built but OFF: see HAPoster, --ha-rest and --mqtt."""
