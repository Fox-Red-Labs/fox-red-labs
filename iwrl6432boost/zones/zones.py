class Tracker:
    """Per-zone occupancy from frames. Time is the frame's own time (see feed). Keeps episodes and a rolling change count."""
    def __init__(self, names):
        self.names = names; n = len(names)
        self.state = [0] * n; self.occ = [False] * n
        self.since = [None] * n; self.last_major = [None] * n; self.peak_state = [0] * n
        self.episodes = [[] for _ in names]       # (on_t, off_t, peak_state, hold_after_major or None)
        self.changes = collections.deque()        # (t, zone, +1/-1)
        self.frames_occ = [0] * n; self.frames = 0
        self.events = []
    def feed(self, t, zs):
        """zs: list of 0..3 per zone. Returns list of (t, zone_index, 'on'|'off', detail) events."""
        ev = []; self.frames += 1
        for i, v in enumerate(zs[:len(self.names)]):
            o = v != 0
            if o: self.frames_occ[i] += 1
            if v == 2: self.last_major[i] = t
            if o and not self.occ[i]:
                self.since[i] = t; self.peak_state[i] = v; self.occ[i] = True
                self.changes.append((t, i, 1)); ev.append((t, i, "on", ""))
            elif o:
                self.peak_state[i] = max(self.peak_state[i], v)
            elif not o and self.occ[i]:
                lm = self.last_major[i]
                hold = round(t - lm, 2) if lm is not None and lm >= self.since[i] else None
                self.episodes[i].append((self.since[i], t, self.peak_state[i], hold))
                self.occ[i] = False
                self.changes.append((t, i, -1)); ev.append((t, i, "off", f"occupied {t - self.since[i]:.1f} s, peak {WORD[self.peak_state[i]]}" + (f", {hold:.1f} s after the last major motion" if hold is not None else "")))
            self.state[i] = v
        while self.changes and self.changes[0][0] < t - 60: self.changes.popleft()
        self.events += [(a, b, c, d) for a, b, c, d in ev]
        return ev
    def changes_last_minute(self): return len(self.changes)

