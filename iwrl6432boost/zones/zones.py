SHIPPED = ["left near", "left far", "right near", "right far"]   # the four boxes in TLV order: x<0 y<3.5, x<0 y>3.51, x>0 y<3.5, x>0 y>3.51
def replay(paths, zfile=ZJSON):
    """Per pass, from the recorded frames: how each of the demo's four shipped boxes lit and cleared, and (seated passes only)
    how often a box on the wrong side of the 3.5 m line lit against the range-profile peak. The profile peak is not used for the walk or
    the empty room: with nobody there it sits on a fixed reflector near 6.5 m."""
    out = {}
    for path in paths:
        rows = list(csv.DictReader(open(path))); tag = os.path.basename(path).replace(".csv", "")
        groups = collections.OrderedDict()
        for r in rows: groups.setdefault((r["pass"], r["round"]), []).append(r)
        for (pas, rnd), g in groups.items():
            if "early" in pas or "backlog" in pas: continue
            fr = [r for r in g if r["frame"]]; cues = {r["event"]: float(r["t"]) for r in g if r["event"]}
            if not fr: continue
            t_ref = cues.get("cue_enter", cues.get("cue_go", float(fr[0]["t"]))); t_leave = cues.get("cue_leave")
            tr = Tracker(SHIPPED); wrong = tot = 0; win_frames = 0; win_lit = [0] * 4; win_any = 0; win_both = 0; win_near = 0; win_far = 0
            for r in fr:
                zs = [int(r["z1"] or 0), int(r["z2"] or 0), int(r["z3"] or 0), int(r["z4"] or 0)]
                tt = float(r["t"]); ev = tr.feed(tt - t_ref, zs)
                inwin = t_leave is not None and t_ref <= tt <= t_leave
                if inwin:
                    win_frames += 1; win_any += 1 if any(zs) else 0
                    for i in range(4): win_lit[i] += 1 if zs[i] else 0
                    win_both += 1 if (zs[0] or zs[2]) and (zs[1] or zs[3]) else 0
                    win_near += 1 if (zs[0] or zs[2]) else 0; win_far += 1 if (zs[1] or zs[3]) else 0
                    if any(zs) and pas.startswith("sit") and r["peak_bin"]:
                        pk = int(r["peak_bin"]) * M_PER_BIN
                        if abs(pk - 3.5) > 0.5:
                            tot += 1
                            if (pk > 3.5 and (zs[0] or zs[2])) or (pk <= 3.5 and (zs[1] or zs[3])): wrong += 1
            for i in range(4):   # close open episodes at the last frame
                if tr.occ[i]: tr.episodes[i].append((tr.since[i], (int(fr[-1]["frame"]) and float(fr[-1]["t"]) - t_ref), tr.peak_state[i], None))
            nm = {"frames": len(fr), "seconds": round(len(fr) * FRAME_S, 1),
                  "episodes_s_from_cue": {SHIPPED[i]: [(round(a_, 1), round(b_, 1)) for a_, b_, _, _ in tr.episodes[i]] for i in range(4) if tr.episodes[i]},
                  "lit_fraction_of_pass": {SHIPPED[i]: round(tr.frames_occ[i] / len(fr), 2) for i in range(4)}}
            if pas.startswith("sit"):
                nm["window_s"] = round(win_frames * FRAME_S, 1)
                nm["window_lit_fraction"] = {SHIPPED[i]: round(win_lit[i] / win_frames, 2) for i in range(4)} if win_frames else None
                nm["window_near_any_lit"] = round(win_near / win_frames, 2) if win_frames else None
                nm["window_far_any_lit"] = round(win_far / win_frames, 2) if win_frames else None
                nm["window_any_lit"] = round(win_any / win_frames, 2) if win_frames else None
                nm["window_near_and_far_both_lit"] = round(win_both / win_frames, 2) if win_frames else None
                nm["opposite_side"] = f"{wrong} of {tot} lit frames" if tot else "n/a"
                nm["opposite_side_fraction"] = round(wrong / tot, 2) if tot else None
            out[f"{tag}:{pas}"] = nm
    print(json.dumps(out, indent=1)); return out

