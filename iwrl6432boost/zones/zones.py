class HAPoster:
    """Posts each zone as binary_sensor.iwrl6432_zone_<slug>, on every change and every 30 s.
    OFF unless run with --ha-rest URL (token in the HA_TOKEN environment variable, never on the command line or in the repo) or --mqtt HOST.
    Roadmap R29 waits on a token; nothing here has talked to a real Home Assistant."""
    def __init__(self, names, rest=None, token=None, mqtt=None, prefix="iwrl6432_zone"):
        self.names = names; self.rest = rest.rstrip("/") if rest else None; self.token = token or os.environ.get("HA_TOKEN")
        self.mqtt_host = mqtt; self.prefix = prefix; self.last = {}; self.sent = {}; self.errors = 0; self.client = None
        if self.mqtt_host:
            import paho.mqtt.client as m   # not installed here; --mqtt is untested
            self.client = m.Client(); self.client.connect(self.mqtt_host); self.client.loop_start()
            for n in names:
                s = slug(n)
                self.client.publish(f"homeassistant/binary_sensor/{prefix}_{s}/config", json.dumps(
                    {"name": f"Radar zone {n}", "unique_id": f"{prefix}_{s}", "device_class": "occupancy",
                     "state_topic": f"iwrl6432/zone/{s}", "payload_on": "ON", "payload_off": "OFF",
                     "device": {"identifiers": ["iwrl6432boost"], "name": "IWRL6432BOOST room zones"}}), retain=True)
    def enabled(self): return bool(self.rest or self.client)
    def update(self, occ, now):
        for i, n in enumerate(self.names):
            s = slug(n); v = bool(occ[i])
            if self.last.get(s) != v or now - self.sent.get(s, 0) >= 30:
                self.last[s] = v; self.sent[s] = now; self._post(s, n, v)
    def _post(self, s, n, v):
        try:
            if self.rest:
                body = json.dumps({"state": "on" if v else "off", "attributes": {"friendly_name": f"Radar zone {n}", "device_class": "occupancy"}}).encode()
                r = urllib.request.Request(f"{self.rest}/api/states/binary_sensor.{self.prefix}_{s}", data=body, method="POST",
                                           headers={"Authorization": f"Bearer {self.token}", "Content-Type": "application/json"})
                urllib.request.urlopen(r, timeout=5).read()
            if self.client: self.client.publish(f"iwrl6432/zone/{s}", "ON" if v else "OFF", retain=True)
        except Exception as e:
            self.errors += 1; print("HA post failed:", type(e).__name__, str(e)[:80], flush=True)

# ------------------------------------------------------------------ radar control
def lock_take():
    try: os.mkdir(LOCK); return True
    except FileExistsError: return False
def lock_drop():
    try: os.rmdir(LOCK)
    except OSError: pass

def other_holders(port):
    out = subprocess.run(["lsof", port], capture_output=True, text=True).stdout.strip().splitlines()[1:]
    return out

def apply(r_cls, port, cfg=CFGOUT, reset=True, log=say):
    """Reset the radar through its debug probe, wait for the CLI, send the cfg, check frames. Returns dict."""
    import radar_link as rl
    res = {"reset": None}
    if reset:
        p = subprocess.run([XDS, "-s", PROBE], capture_output=True, text=True, timeout=30)
        res["reset"] = (p.stdout + p.stderr).strip()[-120:]; log("xds110reset: " + (res["reset"] or "ok")); time.sleep(6)
    r = r_cls(port)
    try:
        st = None
        for _ in range(3):
            r.flush(drain=False)
            ok, rep = r.cmd("version", 2.0)
            if "Version" in rep or "Platform" in rep: st = "cli"; break
        res["cli"] = st; log(f"CLI after reset: {st or 'silent'}")
        if st != "cli": return res
        lines = rl.cfg_lines(cfg, "2x3")
        out = r.apply(lines, log=lambda s: None)
        bad = [(l, rep) for l, ok, rep in out if not ok and not l.startswith("sensorStop")]
        res["lines"] = len(out); res["not_done"] = [f"{l} -> {rep or '(silent)'}" for l, rep in bad]
        log(f"cfg: {len(out)} lines, {len(bad)} not Done" + ("" if not bad else ": " + "; ".join(res["not_done"][:3])))
        time.sleep(1); r.flush(drain=False); t0 = time.time(); n = 0
        while time.time() - t0 < 6: n += len(r.poll())
        res["frames_in_6s"] = n; log(f"frames in 6 s: {n}")
    finally:
        r.close()
    return res

# ------------------------------------------------------------------ run
def run(a):
    import radar_link as rl
    z = load_zones(a.zones); names = [zz["name"] for zz in z["zones"]]
    port = a.port or rl.PORT
    h = other_holders(port)
    if h: sys.exit("port held by another process, stopping:\n" + "\n".join(h))
    if not lock_take(): sys.exit(f"lock {LOCK} exists: another agent has the radar, stopping")
    os.makedirs(RES, exist_ok=True)
    stamp = datetime.datetime.now().strftime("%Y%m%d-%H%M%S"); tag = f"{stamp}-{a.label}"
    fcsv = open(os.path.join(RES, f"zones-{tag}.csv"), "w", newline=""); fw = csv.writer(fcsv)
    fw.writerow(["t_unix", "frame", "bytes", "objs"] + [f"z_{slug(n)}" for n in names] + ["peak_m"])
    ecsv = open(os.path.join(RES, f"zones-{tag}.events.csv"), "w", newline=""); ew = csv.writer(ecsv)
    ew.writerow(["t_unix", "iso", "frame", "zone", "event", "detail"])
    tr = Tracker(names); ha = HAPoster(names, a.ha_rest, mqtt=a.mqtt)
    if ha.enabled(): say("Home Assistant posting is ON")
    state = {"seq": a.seconds}
    r = None; t_start = time.time(); nframes = 0; nbytes = 0; first = last_frame = None; gaps = 0; lastpage = 0
    cues = []
    try:
        r = rl.Radar(port); r.flush(drain=True)
        say(f"streaming {len(names)} zones: " + ", ".join(f"{zz['name']} {zz['y_min']}-{zz['y_max']} m" for zz in z["zones"]))
        t_start = time.time()
        while a.seconds is None or time.time() - t_start < a.seconds:
            batch = r.poll(); k = len(batch)
            for idx, (t, hd, tl) in enumerate(batch):
                tf = t - (k - 1 - idx) * FRAME_S
                zs, peak = decode_zones(tl)
                if zs is None: continue
                if last_frame is not None and hd["frame"] != last_frame + 1: gaps += hd["frame"] - last_frame - 1
                last_frame = hd["frame"]; first = first if first is not None else hd["frame"]
                nframes += 1; nbytes += hd["length"]
                fw.writerow([f"{tf:.3f}", hd["frame"], hd["length"], hd["objs"]] + zs[:len(names)] + ["" if peak is None else peak])
                for (te, zi, e, d) in tr.feed(tf, zs):
                    iso = datetime.datetime.fromtimestamp(te).strftime("%H:%M:%S.%f")[:-3]
                    ew.writerow([f"{te:.3f}", iso, hd["frame"], names[zi], e, d])
                    say(f"{names[zi]:<10} {e.upper():<3} {d}   [{tr.changes_last_minute()} changes in the last minute]")
            now = time.time()
            if now - lastpage >= 1.0:
                lastpage = now; el = max(now - t_start, 1e-9)
                stats = f"{nframes} frames, {nframes / el:.2f} a second, updated {time.strftime('%H:%M:%S')}"
                write_atomic(a.html, page(z, tr, stats, now)); ha.update(tr.occ, now); fcsv.flush(); ecsv.flush()
    except KeyboardInterrupt:
        pass
    finally:
        if r: r.close()
        fcsv.close(); ecsv.close(); lock_drop()
    el = time.time() - t_start
    sm = {"label": a.label, "seconds": round(el, 1), "frames": nframes, "missing_frames": gaps,
          "fps": round(nframes / el, 3) if el else None, "bytes_per_frame": round(nbytes / nframes) if nframes else None,
          "uart_load_pct_of_115200": round(100 * nbytes * 10 / el / 115200, 2) if el else None,
          "zone_on_events": {names[i]: len(tr.episodes[i]) + (1 if tr.occ[i] else 0) for i in range(len(names))},
          "total_on_events": sum(len(tr.episodes[i]) + (1 if tr.occ[i] else 0) for i in range(len(names))),
          "frames_occupied": {names[i]: tr.frames_occ[i] for i in range(len(names))},
          "episodes": {names[i]: [(round(a_ - 0, 3), round(b_, 3), c_, d_) for a_, b_, c_, d_ in tr.episodes[i]] for i in range(len(names))},
          "first_frame": first, "last_frame": last_frame, "log": f"zones-{tag}.csv"}
    json.dump(sm, open(os.path.join(RES, f"zones-{tag}.summary.json"), "w"), indent=1)
    print(json.dumps({k: v for k, v in sm.items() if k != "episodes"}, indent=1))
    return sm

